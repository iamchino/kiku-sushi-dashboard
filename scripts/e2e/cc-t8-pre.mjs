// Compatibilidad: dashboard NUEVO contra una base SIN el SQL 54 (si se pushea antes de correrlo).
import { abrir, BASE, sql as sqlBase, check, resumen } from './lib.mjs'
import { createRequire } from 'node:module'
const XLSX = createRequire(new URL('../../package.json', import.meta.url))('xlsx')
const sql = (q) => sqlBase(q, 'kkpre')
{
  const { browser, page, errores } = await abrir('mozo')
  await page.goto(BASE + '/mesas', { waitUntil: 'networkidle' })
  await page.getByText('7', { exact: true }).first().click()
  await page.getByRole('button', { name: 'Cobrar', exact: true }).click()
  const modal = page.locator('div.fixed', { hasText: 'Cobrar mesa' }).last()
  await modal.getByRole('button', { name: 'Efectivo' }).waitFor()
  await page.waitForTimeout(600)
  check('sin SQL 54: no se ofrece Cuenta corriente', await modal.getByRole('button', { name: 'Cuenta corriente' }).count() === 0)
  await modal.getByRole('button', { name: 'Dividir importe' }).click()
  const opts = await modal.locator('select').first().locator('option').allInnerTexts()
  check('sin SQL 54: tampoco en el pago dividido', !opts.includes('Cuenta corriente'), opts.join('/'))
  await modal.getByRole('button', { name: 'Un medio' }).click()
  await modal.getByRole('button', { name: 'Efectivo' }).click()
  await modal.getByRole('button', { name: /Cerrar mesa sin imprimir/ }).click()
  await modal.waitFor({ state: 'detached', timeout: 15000 }).catch(() => {})
  await page.waitForTimeout(600)
  check('sin SQL 54: el cobro normal anda', sql("select medio_pago||'|'||monto from pagos where pedido_id = '10000000-0000-0000-0000-000000000007'") === 'efectivo|50000.00')
  check('sin SQL 54: la mesa se cierra', sql("select estado from pedidos where id = '10000000-0000-0000-0000-000000000007'") === 'entregado')
  check('mozo: sin errores', errores.length === 0, errores.join(' | '))
  await browser.close()
}
{
  const { browser, page, errores } = await abrir('admin')
  // pago dividido clásico desde Pedidos
  await page.goto(BASE + '/pedidos', { waitUntil: 'networkidle' })
  await page.waitForTimeout(800)
  await page.locator('tr', { hasText: '2x Philadelphia x10' }).locator('button[title="Cerrar pedido"]').click()
  const modal = page.locator('div.fixed', { hasText: 'Medio de pago' }).last()
  await modal.getByText('Dividir pago').click()
  await modal.getByRole('button', { name: 'Agregar medio' }).click()
  const montos = modal.locator('input[placeholder="0"]')
  await montos.nth(0).fill('20000'); await montos.nth(1).fill('16500')
  await modal.locator('select').nth(1).selectOption('transferencia')
  await modal.getByRole('button', { name: 'No imprimir' }).click()
  await modal.getByRole('button', { name: 'Cerrar pedido' }).click()
  await modal.waitFor({ state: 'detached', timeout: 15000 }).catch(() => {})
  await page.waitForTimeout(500)
  check('sin SQL 54: pago dividido clásico anda', sql("select string_agg(medio_pago||':'||monto, ' ' order by medio_pago) from pagos where pedido_id = '10000000-0000-0000-0000-000000000009'") === 'efectivo:20000.00 transferencia:16500.00')

  await page.goto(BASE + '/caja', { waitUntil: 'networkidle' })
  await page.waitForTimeout(1500)
  const caja = await page.locator('main').innerText()
  check('sin SQL 54: Caja carga y suma', /Total cobrado\s*\$86\.500,00/.test(caja), caja.match(/Total cobrado[^]{0,40}/)?.[0])
  check('sin SQL 54: no aparece la fila de canjes', !/Cuenta corriente \(canjes\)/.test(caja))
  const dl = page.waitForEvent('download', { timeout: 20000 })
  await page.getByRole('button', { name: /Exportar Excel/ }).first().click()
  await (await dl).saveAs('shots/reporte-pre.xlsx')
  const wb = XLSX.readFile('shots/reporte-pre.xlsx')
  check('sin SQL 54: Excel sale con las hojas de siempre', wb.SheetNames.join('|') === 'Resumen|Cobros|Pagos|Sueldos por mes', wb.SheetNames.join('|'))
  await page.getByRole('button', { name: /Arqueo/ }).first().click()
  await page.waitForTimeout(1200)
  const arq = await page.locator('main').innerText()
  check('sin SQL 54: arqueo anda', /Efectivo esperado\s*\$90\.000,00/i.test(arq), arq.match(/Efectivo esperado[^]{0,40}/i)?.[0])
  await page.goto(BASE + '/cuentas-corrientes', { waitUntil: 'networkidle' })
  await page.waitForTimeout(700)
  check('sin SQL 54: la sección no existe todavía (redirige)', new URL(page.url()).pathname !== '/cuentas-corrientes', page.url())
  check('admin: sin errores', errores.length === 0, errores.join(' | '))
  await browser.close()
}
process.exit(resumen() ? 1 : 0)

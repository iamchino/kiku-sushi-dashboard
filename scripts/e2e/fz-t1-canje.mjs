check('"Total pagado" no cambió; el canje se informa al lado', /Total pagado: \$127\.686 · con canje: \$310\.000/.test(await txt(panel)), (await txt(panel)).match(/Total pagado[^A-Z]*/)?.[0])
check('el historial del pago guarda el cambio y el motivo', sql(`select count(*) || '|' || max(motivo) from egresos_auditoria where egreso_id = '${F1201}' and evento = 'editado'`) === '1|Se canjeó por una cata')


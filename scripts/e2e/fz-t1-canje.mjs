console.log('— Cash flow: los canjes no son egresos')
await fin.page.getByRole('button', { name: 'Cash flow' }).click()
const tabla = fin.page.getByRole('table')
await tabla.waitFor()
const filaCf = (label) => tabla.locator('tr', { has: fin.page.locator('th', { hasText: new RegExp(`^${label}`) }) }).first()
const celdas = async (label) => (await filaCf(label).locator('td').allInnerTexts()).map(t => t.trim().split('\n')[0])
const m0 = sql("select date_trunc('month', (now() at time zone 'America/Argentina/Buenos_Aires'))::date")
const real = (cats) => Number(sql(`select coalesce(sum(monto), 0) from egresos where estado = 'pagado' and medio_pago <> 'canje' and categoria in (${cats.map(c => `'${c}'`).join(',')}) and date_trunc('month', fecha)::date = '${m0}'`))
const pend = (cats) => Number(sql(`select coalesce(sum(monto), 0) from egresos where estado = 'pendiente' and categoria in (${cats.map(c => `'${c}'`).join(',')}) and greatest(date_trunc('month', vencimiento)::date, '${m0}'::date) = '${m0}'`))
const canjeMes = Number(sql(`select coalesce(sum(monto), 0) from egresos where medio_pago = 'canje' and date_trunc('month', fecha)::date = '${m0}'`))
const titulos = (await tabla.locator('thead th').allInnerTexts()).map(t => t.replace(/\s+/g, ' ').trim())
const col = titulos.findIndex(t => /EN CURSO/i.test(t)) - 1
const merc = await celdas('Mercadería')
check('hay canjes este mes y no están en Mercadería', canjeMes >= 500000 && merc[col] === plata(real(['mercaderia', 'proveedores']) + pend(['mercaderia', 'proveedores'])), `${merc[col]} vs ${plata(real(['mercaderia', 'proveedores']) + pend(['mercaderia', 'proveedores']))} (canjes ${canjeMes})`)
const operativos = real(['mantenimiento', 'marketing']) + pend(['mantenimiento', 'marketing'])
check('ni en Operativos (el canje de marketing)', operativos === 0 && (await celdas('Operativos'))[col] === '—', (await celdas('Operativos'))[col])

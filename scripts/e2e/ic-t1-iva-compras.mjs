// IVA de las compras (SQL 61), de punta a punta en el navegador: la factura de
// la consulta de administración ($16.644,03 con IVA 21 % de $2.888,63), una
// pendiente al 10,5 %, una con varias alícuotas, corregir monto e IVA juntos
// (para arriba y para abajo), sacar el IVA, el recuadro de Finanzas → Resumen
// y la hoja "IVA compras" del Excel del contador.
import { abrir, BASE, sql as sqlBase, check, resumen } from './lib.mjs'
import { createRequire } from 'node:module'
const XLSX = createRequire(new URL('../../package.json', import.meta.url))('xlsx')
const DB = process.env.DB || 'kkic'
const sql = (q) => sqlBase(q, DB)
async function hasta(fn, ms = 8000) {
  const fin = Date.now() + ms
  for (;;) { const v = await fn(); if (v || Date.now() > fin) return v; await new Promise(r => setTimeout(r, 200)) }
}
const txt = async (loc) => (await loc.innerText()).replace(/\s+/g, ' ')
const ddmm = (iso) => `${iso.slice(8, 10)}/${iso.slice(5, 7)}/${iso.slice(0, 4)}`
const xp = (label) => `xpath=.//label[starts-with(normalize-space(.), "${label}")]/following-sibling::*[1]/descendant-or-self::*[self::input or self::select or self::textarea][1] | .//label[starts-with(normalize-space(.), "${label}")]/following-sibling::select[1]`

const HOY = sql("select to_char((now() at time zone 'America/Argentina/Buenos_Aires')::date, 'YYYY-MM-DD')")
// La fecha de la factura: dos días antes, sin salir del mes.
const FECHA_F = Number(HOY.slice(8, 10)) >= 3 ? sql(`select to_char('${HOY}'::date - 2, 'YYYY-MM-DD')`) : HOY
const VENC = sql(`select to_char('${HOY}'::date + 10, 'YYYY-MM-DD')`)
const eg = (desc, cols = "monto || '|' || coalesce(iva_credito::text, 'sin iva') || '|' || coalesce(iva_alicuota, '-') || '|' || coalesce(factura_fecha::text, '-')") =>
  sql(`select ${cols} from egresos where descripcion = '${desc}'`)

const { browser, page, errores } = await abrir('finanzas', { viewport: { width: 1360, height: 1500 } })
await page.goto(BASE + '/caja', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: /^Pagos$/ }).click()
const panel = page.locator('section', { has: page.getByRole('heading', { name: 'Pagos' }) }).first()
const modal = page.locator('.fixed.inset-0').filter({ has: page.getByRole('heading', { name: /Registrar pago|Editar pago/ }) })
const campo = (label) => modal.locator(xp(label)).first()
const iva = modal.locator('[data-iva-factura]')
const campoIva = (label) => iva.locator(xp(label)).first()
const guardar = modal.locator('button.w-full').last()
const filaPago = (d) => panel.locator('div.rounded-xl', { hasText: d }).last()

console.log('— la factura de la consulta: $16.644,03 con IVA 21 %')
await page.getByRole('button', { name: /Registrar pago/ }).first().click()
await modal.waitFor()
await campo('Categoría').selectOption('mercaderia')
await campo('Medio de pago').selectOption('transferencia')
await campo('Descripción').fill('Tapas de copetín')
await campo('Monto').fill('16644.03')
check('ofrece «Cargar el IVA de la factura»', /Factura A de un proveedor: su IVA es crédito fiscal/.test(await txt(modal.locator('[data-abrir-iva]'))))
await modal.locator('[data-abrir-iva]').click()
await iva.waitFor()
check('arranca en 21 % y calcula el IVA del monto: $2.888,63', await campoIva('IVA ($)').inputValue() === '2888.63'
  && await iva.getByRole('button', { name: '21 %' }).getAttribute('aria-pressed') === 'true', await campoIva('IVA ($)').inputValue())
check('muestra lo que no es IVA: $13.755,40', (await txt(iva.locator('[data-eco-iva]'))).startsWith('Sin IVA (neto y otros): $13.755,40 · IVA: $2.888,63'), await txt(iva.locator('[data-eco-iva]')))
check('la fecha de la factura arranca en la del pago (hoy)', await campoIva('Fecha de la factura').inputValue() === HOY)
await iva.getByRole('button', { name: '10,5 %' }).click()
check('al cambiar a 10,5 % se recalcula ($1.581,56)', await campoIva('IVA ($)').inputValue() === '1581.56', await campoIva('IVA ($)').inputValue())
await iva.getByRole('button', { name: '21 %' }).click()
await campoIva('IVA ($)').fill('20000')
check('un IVA mayor que el monto no deja guardar', /no puede ser mayor que el monto del pago/.test(await txt(iva.locator('[data-eco-iva]'))) && await guardar.isDisabled())
await campoIva('IVA ($)').fill('2.888,63')
check('acepta el formato con punto de miles y coma', (await txt(iva.locator('[data-eco-iva]'))).includes('IVA: $2.888,63') && !(await guardar.isDisabled()))
await campoIva('Fecha de la factura').fill(FECHA_F)
await iva.scrollIntoViewIfNeeded()
await page.screenshot({ path: 'shots/ic-1-registrar.png' })
await guardar.click()
await modal.waitFor({ state: 'hidden' })
check('avisa el IVA guardado', await hasta(async () => (await txt(panel)).includes('IVA de la factura: $2.888,63 (crédito fiscal).')), (await txt(panel)).slice(0, 300))
check('la base: $16.644,03 · IVA 2888.63 · 21 · fecha de la factura', eg('Tapas de copetín') === `16644.03|2888.63|21|${FECHA_F}`, eg('Tapas de copetín'))
check('la fila lleva «IVA $2.888,63»', await hasta(async () => (await filaPago('Tapas de copetín').locator('[data-iva-chip]').count()) === 1)
  && (await txt(filaPago('Tapas de copetín').locator('[data-iva-chip]'))) === 'IVA $2.888,63')
check('con el detalle al pasar el mouse', /IVA 21 % · crédito fiscal · factura del/.test(await filaPago('Tapas de copetín').locator('[data-iva-chip]').getAttribute('title')))

console.log('— corregir monto e IVA a la vez')
await filaPago('Tapas de copetín').getByTitle('Corregir este pago').click()
await modal.waitFor()
check('al corregir, el IVA ya está cargado', await iva.count() === 1 && await campoIva('IVA ($)').inputValue() === '2888.63'
  && await iva.getByRole('button', { name: '21 %' }).getAttribute('aria-pressed') === 'true' && await campoIva('Fecha de la factura').inputValue() === FECHA_F)
await campo('Monto').fill('2000')
check('bajar el monto por debajo del IVA avisa y no deja guardar', /no puede ser mayor que el monto/.test(await txt(iva.locator('[data-eco-iva]'))) && await guardar.isDisabled())
await campo('Monto').fill('12100')
await iva.getByRole('button', { name: '21 %' }).click()
check('al tocar 21 % se recalcula del monto nuevo: $2.100', await campoIva('IVA ($)').inputValue() === '2100')
await guardar.click()
await modal.waitFor({ state: 'hidden' })
check('para abajo: $12.100 con IVA $2.100 (el IVA se guarda primero)', await hasta(async () => eg('Tapas de copetín') === `12100.00|2100.00|21|${FECHA_F}`), eg('Tapas de copetín'))
await filaPago('Tapas de copetín').getByTitle('Corregir este pago').click()
await modal.waitFor()
await campo('Monto').fill('242000')
await iva.getByRole('button', { name: '21 %' }).click()
await guardar.click()
await modal.waitFor({ state: 'hidden' })
check('para arriba: $242.000 con IVA $42.000 (el monto se guarda primero)', await hasta(async () => eg('Tapas de copetín') === `242000.00|42000.00|21|${FECHA_F}`), eg('Tapas de copetín'))
check('el historial del pago registra los cambios del IVA',
  Number(sql(`select count(*) from egresos_auditoria a join egresos e on e.id = a.egreso_id where e.descripcion = 'Tapas de copetín' and a.detalle -> 'cambios' ? 'iva_credito'`)) >= 2)

console.log('— una pendiente al 10,5 %')
await page.getByRole('button', { name: /Registrar pago/ }).first().click()
await modal.waitFor()
await campo('Categoría').selectOption('proveedores')
await campo('Medio de pago').selectOption('transferencia')
await campo('Descripción').fill('Verdulería quincena')
await campo('Monto').fill('110500')
await campo('Estado').selectOption('pendiente')
await campo('Vencimiento').fill(VENC)
await modal.locator('[data-abrir-iva]').click()
await iva.getByRole('button', { name: '10,5 %' }).click()
check('10,5 % de $110.500: $10.500', await campoIva('IVA ($)').inputValue() === '10500')
await campoIva('Fecha de la factura').fill(FECHA_F)
await guardar.click()
await modal.waitFor({ state: 'hidden' })
check('la base: pendiente, IVA 10500 al 10.5', await hasta(async () => eg('Verdulería quincena') === `110500.00|10500.00|10.5|${FECHA_F}`)
  && eg('Verdulería quincena', 'estado') === 'pendiente', eg('Verdulería quincena'))

console.log('— una con varias alícuotas, y después sacarle el IVA')
await page.getByRole('button', { name: /Registrar pago/ }).first().click()
await modal.waitFor()
await campo('Categoría').selectOption('mercaderia')
await campo('Medio de pago').selectOption('transferencia')
await campo('Descripción').fill('Almacén varios')
await campo('Monto').fill('50000')
await modal.locator('[data-abrir-iva]').click()
await iva.getByRole('button', { name: 'Varias' }).click()
check('con «Varias» explica que se escribe la suma', (await txt(iva.locator('[data-eco-iva]'))).includes('con varias alícuotas, escribí la suma de los renglones de IVA'))
await campoIva('IVA ($)').fill('7000')
await guardar.click()
await modal.waitFor({ state: 'hidden' })
check('la base: IVA 7000, alícuota «mixto»', await hasta(async () => eg('Almacén varios') === `50000.00|7000.00|mixto|${HOY}`), eg('Almacén varios'))
await filaPago('Almacén varios').getByTitle('Corregir este pago').click()
await modal.waitFor()
await iva.getByRole('button', { name: 'Sacar el IVA' }).click()
check('sin IVA, vuelve el botón para cargarlo', await iva.count() === 0 && await modal.locator('[data-abrir-iva]').count() === 1)
await guardar.click()
await modal.waitFor({ state: 'hidden' })
check('avisa que se sacó', await hasta(async () => (await txt(panel)).includes('Se sacó el IVA de la factura.')))
check('la base: sin IVA, sin alícuota, sin fecha de factura', eg('Almacén varios') === '50000.00|sin iva|-|-', eg('Almacén varios'))
check('la fila ya no lleva la marca', await filaPago('Almacén varios').locator('[data-iva-chip]').count() === 0)

console.log('— un sueldo no lleva IVA')
await page.getByRole('button', { name: /Registrar pago/ }).first().click()
await modal.waitFor()
await campo('Categoría').selectOption('sueldos')
check('con categoría Sueldos no aparece la sección', await modal.locator('[data-abrir-iva]').count() === 0 && await iva.count() === 0)
await modal.getByRole('button', { name: '×' }).click()
check('sin errores de consola (Caja)', errores.length === 0, errores.join(' || '))

console.log('— Finanzas → Resumen: el recuadro «IVA de las compras»')
await page.goto(BASE + '/finanzas', { waitUntil: 'networkidle' })
const caja = page.locator('[data-iva-compras]')
await caja.waitFor({ timeout: 15000 })
await hasta(async () => (await caja.locator('[data-iva-compras-total]').count()) === 1, 10000)
const t = await txt(caja)
check('suma $52.500 de IVA en 2 facturas ($352.500 en total)', (await txt(caja.locator('[data-iva-compras-total]'))).includes('$52.500') && t.includes('$352.500') && t.includes('2 facturas · sin IVA $300.000'), t)
check('por alícuota: 21 % $42.000 · 10,5 % $10.500', t.includes('21 %: $42.000 · 10,5 %: $10.500'), t)
const saldo = await txt(caja.locator('[data-iva-saldo]'))
const m = saldo.match(/IVA ventas \$([\d.,]+) − IVA compras \$52\.500/)
const ventas = m ? Number(m[1].replace(/\./g, '').replace(',', '.')) : NaN
const dif = Math.round((ventas - 52500) * 100) / 100
const fmt = (n) => `$${Math.abs(n).toLocaleString('es-AR', { minimumFractionDigits: Math.round(Math.abs(n) * 100) % 100 ? 2 : 0, maximumFractionDigits: 2 })}`
check('saldo estimado = IVA de las ventas − IVA de las compras', m && ventas >= 0
  && saldo.includes(dif > 0 ? 'A PAGAR' : 'A FAVOR') && saldo.includes(fmt(dif)), saldo)
check('aclara que es una estimación y que lo calcula el contador', /no incluye percepciones, retenciones ni el saldo a favor de meses anteriores/.test(t))
await caja.scrollIntoViewIfNeeded()
await page.screenshot({ path: 'shots/ic-2-finanzas.png' })
check('sin errores de consola (Finanzas)', errores.length === 0, errores.join(' || '))
await browser.close()

console.log('— el Excel del contador (admin, Caja)')
const adm = await abrir('admin', { viewport: { width: 1360, height: 1100 } })
await adm.page.goto(BASE + '/caja', { waitUntil: 'networkidle' })
await adm.page.getByRole('button', { name: 'Últ. 30 días', exact: true }).click()
await adm.page.waitForTimeout(800)
const dl = adm.page.waitForEvent('download', { timeout: 30000 })
await adm.page.getByRole('button', { name: 'Exportar Excel' }).click()
await (await dl).saveAs('shots/ic-reporte.xlsx')
const wb = XLSX.readFile('shots/ic-reporte.xlsx')
const hoja = XLSX.utils.sheet_to_json(wb.Sheets['IVA compras'] || {})
check('hoja «IVA compras»: 2 facturas + total', hoja.length === 3, wb.SheetNames.join(' | '))
check('con la columna del crédito fiscal y el total', hoja.at(-1)?.['IVA (crédito fiscal)'] === 52500 && hoja.at(-1)?.['Total'] === 352500, JSON.stringify(hoja.at(-1)))
const tapas = hoja.find(r => r['Descripción'] === 'Tapas de copetín')
check('cada factura con su fecha, alícuota, sin IVA y estado', tapas?.['Fecha de la factura'] === ddmm(FECHA_F) && tapas?.['Alícuota'] === '21 %' && tapas?.['Sin IVA (neto y otros)'] === 200000 && tapas?.['Estado'] === 'Pagada'
  && hoja.find(r => r['Descripción'] === 'Verdulería quincena')?.['Estado'] === 'Pendiente de pago', JSON.stringify(tapas))
const res = XLSX.utils.sheet_to_json(wb.Sheets['Resumen'], { header: 1 })
check('el Resumen trae «IVA de las compras · crédito fiscal» $52.500', res.find(r => String(r[0] || '') === 'IVA de las compras · crédito fiscal')?.[1] === 52500)
check('sin errores de consola (admin)', adm.errores.length === 0, adm.errores.join(' || '))
await adm.browser.close()

console.log('— solo lectura (administración): ve el recuadro')
const lec = await abrir('administracion', { viewport: { width: 1360, height: 1100 } })
await lec.page.goto(BASE + '/finanzas', { waitUntil: 'networkidle' })
await lec.page.locator('[data-iva-compras-total]').waitFor({ timeout: 15000 })
check('solo lectura: ve $52.500', (await txt(lec.page.locator('[data-iva-compras-total]'))).includes('$52.500'))
check('sin errores de consola (solo lectura)', lec.errores.length === 0, lec.errores.join(' || '))
await lec.browser.close()
process.exit(resumen() ? 1 : 0)

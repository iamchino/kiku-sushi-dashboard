// Finanzas → Resumen → "Disponible hoy": caja del día, caja fuerte y el saldo
// de cada cuenta del negocio cargado a mano (SQL 59). Como finanzas (ve todo),
// como rol de solo lectura y en el celular.
import { abrir, BASE, sql as sqlBase, check, resumen } from './lib.mjs'
const DB = process.env.DB || 'kkfz'
const sql = (q) => sqlBase(q, DB)
async function hasta(fn, ms = 8000) {
  const fin = Date.now() + ms
  for (;;) { const v = await fn(); if (v || Date.now() > fin) return v; await new Promise(r => setTimeout(r, 200)) }
}
const txt = async (loc) => (await loc.innerText()).replace(/\s+/g, ' ')
const hoy = sql("select to_char((now() at time zone 'America/Argentina/Buenos_Aires')::date, 'DD/MM/YYYY')")
const GALICIA = sql("select id from cuentas_negocio where tipo = 'banco' order by orden, created_at limit 1")
const MP = sql("select id from cuentas_negocio where tipo = 'billetera' order by orden, created_at limit 1")
const N_GAL = 'Kiku SAS — Galicia', N_MP = 'Mercado Pago KIKU SUSHI'

const { browser, page, errores } = await abrir('finanzas', { viewport: { width: 1360, height: 1300 } })
await page.goto(BASE + '/finanzas', { waitUntil: 'networkidle' })
const card = page.locator('[data-disponible]')
await card.waitFor({ timeout: 15000 })
const fila = (nombre) => card.locator(`[data-disponible-fila="${nombre}"]`)
const total = () => txt(card.locator('[data-disponible-total]'))
const modal = page.locator('.fixed.inset-0').filter({ has: page.locator('[data-modal-saldo]') })
const actualizar = async () => { await card.getByRole('button', { name: 'Actualizar el disponible' }).click(); await page.waitForTimeout(700) }

console.log('— el recuadro, antes de cargar ningún saldo')
await hasta(async () => /\$170\.000/.test(await txt(fila('Caja del día'))))
check('caja del día: el efectivo esperado del turno abierto (fondo + cobros en efectivo)', /Caja del día Turno abierto · efectivo esperado \$170\.000/.test(await txt(fila('Caja del día'))), await txt(fila('Caja del día')))
check('caja fuerte: su saldo', /Caja fuerte Efectivo guardado \$250\.000/.test(await txt(fila('Caja fuerte'))) && sql("select sum(case when tipo = 'deposito' then monto else -monto end) from caja_fuerte_movimientos") === '250000.00', await txt(fila('Caja fuerte')))
check('cada cuenta del negocio, todavía sin saldo', /Sin saldo cargado todavía — Cargar saldo/.test(await txt(fila(N_GAL))) && /Sin saldo cargado todavía — Cargar saldo/.test(await txt(fila(N_MP))), await txt(fila(N_GAL)))
check('el total suma lo que hay y dice qué falta', await total() === '$420.000' && /Total cargado/i.test(await txt(card))
  && await txt(card.locator('[data-disponible-faltan]')) === `Sin contar ${N_GAL} y ${N_MP}`, `${await total()} · ${await txt(card)}`.slice(0, 300))
check('aclara que no se conecta al banco y que no depende del período', /el sistema no se conecta al banco/.test(await txt(card)) && /No depende del período/.test(await txt(card)))

console.log('— el efectivo esperado es el mismo número que muestra el arqueo')
await page.goto(BASE + '/caja', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: /Arqueo/ }).first().click()
check('Arqueo: efectivo esperado $170.000,00', await hasta(async () => /Efectivo esperado \$170\.000,00/i.test(await txt(page.locator('main')))))
await page.goto(BASE + '/finanzas', { waitUntil: 'networkidle' })
await card.waitFor()

console.log('— cargar el saldo del banco')
await fila(N_GAL).getByRole('button', { name: 'Cargar saldo' }).click()
await modal.waitFor()
const guardar = modal.getByRole('button', { name: 'Guardar saldo' })
const campoSaldo = modal.locator('input[inputmode="decimal"]')
check('el modal dice de qué cuenta es y que no se conecta al banco', /Saldo de Kiku SAS — Galicia/.test(await txt(modal)) && /no se conecta al banco/.test(await txt(modal)))
check('sin saldo escrito no se puede guardar', await guardar.isDisabled())
await campoSaldo.fill('abc')
await guardar.click()
check('texto que no es un número: lo dice y no guarda', /Ese saldo no es un número/.test(await txt(modal.locator('[data-error-saldo]'))) && sql('select count(*) from cuentas_negocio_saldos') === '0')
await campoSaldo.fill('500.000')
check('repite el monto con los puntos antes de guardar', /Vas a guardar \$500\.000/.test(await txt(modal.locator('[data-eco-saldo]'))), await txt(modal))
await page.screenshot({ path: 'shots/fz-2-cargar-saldo.png' })
await guardar.click()
await modal.waitFor({ state: 'hidden' })
await hasta(async () => /\$500\.000/.test(await txt(fila(N_GAL))))
check('la cuenta muestra el saldo, de cuándo es y quién lo cargó', new RegExp(`Saldo del ${hoy} \\(hoy\\) · lo cargó Yamile Prueba \\$500\\.000 Actualizar`).test(await txt(fila(N_GAL))), await txt(fila(N_GAL)))
check('avisa que se guardó', /Saldo de Kiku SAS — Galicia actualizado: \$500\.000\./.test(await txt(card.locator('[data-disponible-aviso]'))))
check('el total lo suma y ya no lo cuenta entre lo que falta', await total() === '$920.000' && await txt(card.locator('[data-disponible-faltan]')) === `Sin contar ${N_MP}`, await total())
check('quedó en la base con fecha de hoy y el nombre de quien lo cargó', sql(`select saldo || '|' || (fecha = (now() at time zone 'America/Argentina/Buenos_Aires')::date) || '|' || usuario_nombre from cuentas_negocio_saldos where cuenta_id = '${GALICIA}'`) === '500000.00|true|Yamile Prueba')

console.log('— un saldo con centavos y el total completo')
await fila(N_MP).getByRole('button', { name: 'Cargar saldo' }).click()
await modal.waitFor()
await campoSaldo.fill('85.500,50')
check('acepta el formato argentino y muestra los centavos', /Vas a guardar \$85\.500,50/.test(await txt(modal.locator('[data-eco-saldo]'))), await txt(modal))
await modal.locator('input').nth(2).fill('antes de las tarjetas')
await guardar.click()
await modal.waitFor({ state: 'hidden' })
await hasta(async () => /\$85\.500,50/.test(await txt(fila(N_MP))))
check('con todo cargado el total es completo', await total() === '$1.005.500,50' && await card.locator('[data-disponible-faltan]').count() === 0 && !/Total cargado/i.test(await txt(card)), `${await total()}`)
check('la nota queda guardada', sql(`select nota from cuentas_negocio_saldos where cuenta_id = '${MP}'`) === 'antes de las tarjetas')
await page.screenshot({ path: 'shots/fz-1-disponible.png' })

console.log('— actualizar, fecha futura y un saldo más viejo que el vigente')
await fila(N_GAL).getByRole('button', { name: 'Actualizar' }).click()
await modal.waitFor()
await campoSaldo.fill('480000')
check('al actualizar muestra el saldo anterior', /Vas a guardar \$480\.000 · el anterior era \$500\.000/.test(await txt(modal.locator('[data-eco-saldo]'))), await txt(modal))
const campoFecha = modal.locator('input[type="date"]')
await campoFecha.fill(sql("select ((now() at time zone 'America/Argentina/Buenos_Aires')::date + 1)::text"))
await guardar.click()
check('una fecha futura se rechaza', /La fecha del saldo no puede ser futura/.test(await txt(modal.locator('[data-error-saldo]'))))
await campoFecha.fill(sql("select ((now() at time zone 'America/Argentina/Buenos_Aires')::date - 1)::text"))
check('con una fecha anterior al saldo vigente, avisa que no lo cambia', /Ya hay un saldo más nuevo, del .*: este queda en el historial y no cambia el disponible/.test(await txt(modal.locator('[data-saldo-viejo]'))), await txt(modal))
await guardar.click()
await modal.waitFor({ state: 'hidden' })
await hasta(async () => /guardado en el historial/.test(await txt(card.locator('[data-disponible-aviso]'))))
check('queda en el historial y el vigente sigue siendo el de hoy', /\$500\.000/.test(await txt(fila(N_GAL))) && await total() === '$1.005.500,50'
  && sql(`select count(*) || '|' || string_agg(saldo::text, ',' order by fecha) from cuentas_negocio_saldos where cuenta_id = '${GALICIA}'`) === '2|480000.00,500000.00', await txt(fila(N_GAL)))
await fila(N_GAL).getByRole('button', { name: 'Actualizar' }).click()
await modal.waitFor()
await campoSaldo.fill('520000')
await guardar.click()
await modal.waitFor({ state: 'hidden' })
await hasta(async () => /\$520\.000/.test(await txt(fila(N_GAL))))
check('el mismo día, manda el último que se cargó', /\$520\.000/.test(await txt(fila(N_GAL))) && await total() === '$1.025.500,50', await total())

console.log('— el saldo queda viejo: pagos posteriores y más de una semana')
// Un pago por transferencia desde Galicia, registrado después del saldo.
sql(`insert into egresos (fecha, categoria, descripcion, monto, medio_pago, estado, pagado_desde, cuenta_id, created_at)
     values ((now() at time zone 'America/Argentina/Buenos_Aires')::date, 'servicios', 'Luz', 80000, 'transferencia', 'pagado', 'banco', '${GALICIA}', now() + interval '1 minute')`)
sql(`update cuentas_negocio_saldos set fecha = fecha - 8 where cuenta_id = '${MP}'`)
await actualizar()
await hasta(async () => (await card.locator('[data-disponible-viejo]').count()) === 2)
check('avisa lo que salió por transferencia después del saldo', /Después de ese saldo se pagó \$80\.000 por transferencia desde esta cuenta\. Conviene actualizarlo/.test(await txt(fila(N_GAL))), await txt(fila(N_GAL)))
check('no lo resta del saldo (el sistema no ve lo que entra)', /\$520\.000/.test(await txt(fila(N_GAL))))
check('un saldo de más de una semana lo dice', /\(hace 8 días\)/.test(await txt(fila(N_MP))) && /Tiene más de una semana: conviene actualizarlo/.test(await txt(fila(N_MP))), await txt(fila(N_MP)))
await page.screenshot({ path: 'shots/fz-3-saldo-viejo.png' })

console.log('— con la caja cerrada')
sql(`update caja_turnos set estado = 'cerrado', cierre_at = now(), cierre_monto = 30000,
       denominaciones_cierre = '{"medios":{"efectivo":{"esperado":170000,"contado":30000}}}'::jsonb
     where id = '20000000-0000-0000-0000-000000000001'`)
await actualizar()
await hasta(async () => /Caja cerrada/.test(await txt(fila('Caja del día'))))
check('muestra lo que quedó en el cajón del último cierre', new RegExp(`Caja cerrada · lo que quedó en el cajón del cierre del ${hoy} \\$30\\.000`).test(await txt(fila('Caja del día'))), await txt(fila('Caja del día')))
check('sin errores de consola (finanzas)', errores.length === 0, errores.join(' || '))
await browser.close()

console.log('— rol de solo lectura de Finanzas, sin Caja ni caja fuerte')
const lec = await abrir('administracion', { viewport: { width: 1360, height: 1100 } })
await lec.page.goto(BASE + '/finanzas', { waitUntil: 'networkidle' })
const cardL = lec.page.locator('[data-disponible]')
await cardL.waitFor({ timeout: 15000 })
await hasta(async () => /\$520\.000/.test(await txt(cardL)))
const tL = await txt(cardL)
check('ve los saldos de los bancos', /Kiku SAS — Galicia .*\$520\.000/.test(tL) && /\$85\.500,50/.test(tL), tL.slice(0, 400))
check('no puede cargarlos', await cardL.getByRole('button', { name: /Cargar saldo|^Actualizar$/ }).count() === 0)
check('lo que no puede ver lo dice, sin inventar un cero', /Caja del día Sin acceso a Caja —/.test(tL) && /Caja fuerte Sin acceso a la caja fuerte —/.test(tL)
  && /Sin contar Caja del día y Caja fuerte/.test(tL) && await txt(cardL.locator('[data-disponible-total]')) === '$605.500,50', tL.slice(0, 400))
check('y la base tampoco lo deja', (() => { try { sql(`set role authenticated; select set_config('request.jwt.claims', '{"sub":"00000000-0000-0000-0000-0000000000d1","role":"authenticated","app_metadata":{"role":"administracion"}}', false); select public.cuenta_negocio_informar_saldo('${GALICIA}', 1)`); return false } catch (e) { return /No tenés permiso/.test(String(e.stderr || e.message)) } })())
check('sin errores de consola (solo lectura)', lec.errores.length === 0, lec.errores.join(' || '))
await lec.browser.close()

console.log('— en el celular')
const cel = await abrir('finanzas', { viewport: { width: 390, height: 844 } })
await cel.page.goto(BASE + '/finanzas', { waitUntil: 'networkidle' })
const cardC = cel.page.locator('[data-disponible]')
await cardC.waitFor({ timeout: 15000 })
await hasta(async () => /\$520\.000/.test(await txt(cardC)))
await cardC.scrollIntoViewIfNeeded()
const ancho = await cel.page.evaluate(() => { const m = document.querySelector('main'); return [m.scrollWidth, m.clientWidth] })
check('entra en el ancho de la pantalla, sin scroll horizontal', ancho[0] <= ancho[1] + 1, ancho.join(' vs '))
check('se leen el total, las cuentas y el botón', /\$\d/.test(await txt(cardC.locator('[data-disponible-total]'))) && await cardC.getByRole('button', { name: 'Actualizar', exact: true }).count() === 2)
await cel.page.screenshot({ path: 'shots/fz-4-disponible-celular.png' })
await cardC.getByRole('button', { name: 'Actualizar', exact: true }).first().click()
const modalC = cel.page.locator('.fixed.inset-0').filter({ has: cel.page.locator('[data-modal-saldo]') })
await modalC.waitFor()
const caja = await modalC.locator('[data-modal-saldo]').boundingBox()
check('el modal entra en el celular', caja && caja.x >= 0 && caja.x + caja.width <= 391, JSON.stringify(caja))
check('sin errores de consola (celular)', cel.errores.length === 0, cel.errores.join(' || '))
await cel.browser.close()
process.exit(resumen() ? 1 : 0)

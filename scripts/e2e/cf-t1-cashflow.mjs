// Finanzas → Cash flow, como finanzas, contra Postgres real con datos de ejemplo.
import { abrir, BASE, sql as sqlBase, check, resumen } from './lib.mjs'
import { createRequire } from 'node:module'
const XLSX = createRequire(new URL('../../package.json', import.meta.url))('xlsx')
const DB = process.env.DB || 'kkcf'
const sql = (q) => sqlBase(q, DB)
const plata = (n) => `${Number(n) < 0 ? '-' : ''}$${Math.abs(Math.round(Number(n))).toLocaleString('es-AR')}`

const m0 = sql("select date_trunc('month', (now() at time zone 'America/Argentina/Buenos_Aires'))::date")
const mes = (n) => sql(`select ('${m0}'::date + interval '${n} month')::date`)
const [mAnt, m1, m2, m3, m4] = [mes(-1), mes(1), mes(2), mes(3), mes(4)]
const cobrado = (m) => Number(sql(`select coalesce(sum(monto),0) from pagos where medio_pago <> 'cuenta_corriente' and date_trunc('month', created_at at time zone 'America/Argentina/Buenos_Aires')::date = '${m}'`))
const pagado = (m, cats) => Number(sql(`select coalesce(sum(monto),0) from egresos where estado = 'pagado' and categoria in (${cats.map(c => `'${c}'`).join(',')}) and date_trunc('month', fecha)::date = '${m}'`))

const { browser, page, errores } = await abrir('finanzas', { viewport: { width: 1440, height: 1000 } })
await page.goto(BASE + '/finanzas', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Cash flow' }).click()
const tabla = page.getByRole('table')
await tabla.waitFor()
const fila = (label) => tabla.locator('tr', { has: page.locator('th', { hasText: new RegExp(`^${label}`) }) }).first()
const celdas = async (label) => (await fila(label).locator('td').allInnerTexts()).map(t => t.trim().split('\n')[0])
const titulos = (await tabla.locator('thead th').allInnerTexts()).map(t => t.replace(/\s+/g, ' ').trim())

console.log('— lo real coincide con la base')
check('6 meses: uno pasado, el actual y cuatro futuros', titulos.length === 8 && /REAL/i.test(titulos[1]) && /EN CURSO/i.test(titulos[2]) && /ESTIMADO/i.test(titulos[3]) && titulos[7] === 'Total', titulos.join(' | '))
const ing = await celdas('Total ingresos')
check('ingresos del mes pasado = cobros (más de 1000 pagos, sumados en la base)', ing[0] === plata(cobrado(mAnt)) && Number(sql(`select count(*) from pagos where date_trunc('month', created_at at time zone 'America/Argentina/Buenos_Aires')::date = '${mAnt}'`)) > 1000, `${ing[0]} vs ${plata(cobrado(mAnt))}`)
check('ingresos del mes en curso = cobrado hasta hoy (sin estimado)', ing[1] === plata(cobrado(m0)), `${ing[1]} vs ${plata(cobrado(m0))}`)
const merc = await celdas('Mercadería')
check('Mercadería agrupa mercadería + proveedores', merc[0] === plata(pagado(mAnt, ['mercaderia', 'proveedores'])), merc[0])
check('Local y servicios agrupa alquiler + servicios', (await celdas('Local y servicios'))[0] === plata(pagado(mAnt, ['alquiler', 'servicios'])))
check('Operativos agrupa mantenimiento + marketing', (await celdas('Operativos'))[0] === plata(pagado(mAnt, ['mantenimiento', 'marketing'])))
check('Comisiones y financieros (categoría nueva)', (await celdas('Comisiones y financieros'))[0] === plata(pagado(mAnt, ['comisiones'])))
const totalEg = await celdas('Total egresos')
check('total de egresos del mes pasado', totalEg[0] === plata(Number(sql(`select sum(monto) from egresos where estado='pagado' and date_trunc('month', fecha)::date = '${mAnt}'`))), totalEg[0])
check('flujo neto del mes pasado', (await celdas('Flujo neto del mes'))[0] === plata(cobrado(mAnt) - Number(sql(`select sum(monto) from egresos where estado='pagado' and date_trunc('month', fecha)::date = '${mAnt}'`))))
// mes en curso: pagado + pendientes (incluye la factura vencida del mes pasado)
const provActual = pagado(m0, ['mercaderia', 'proveedores']) + 640000
check('mes en curso: pagado + pendiente, con lo vencido impago', merc[1] === plata(provActual), `${merc[1]} vs ${plata(provActual)}`)
check('futuro: pendientes cargados por mes de vencimiento', (await celdas('Local y servicios'))[2] === '$2.050.000' && (await celdas('Inversiones y otros')).slice(2, 5).join() === '$900.000,$900.000,$900.000')
check('pendientes cargados por mes', (await celdas('Pagos pendientes ya cargados'))[2] === '$2.950.000')
check('avisa el pendiente sin fecha', await page.getByText(/1 pago pendiente sin fecha de vencimiento por \$310\.000/).count() === 1)
check('avisa que falta estimar los ingresos del mes', await page.getByText(/falta estimar los ingresos del mes/).count() === 1)
check('sin saldo cargado, la fila Saldo final queda vacía', (await celdas('Saldo final')).every(c => c === '—'))
await page.screenshot({ path: 'shots/cf-01-sin-estimados.png', fullPage: true })

console.log('— estimar una celda')
const celdaBtn = (label, col) => fila(label).locator('td').nth(col).getByRole('button', { name: /Editar estimado/ })
await celdaBtn('Total ingresos', 2).click()
await page.keyboard.type('44.500.000'); await page.keyboard.press('Enter')
await page.waitForTimeout(500)
check('estimado guardado (acepta puntos de miles)', sql(`select monto from cashflow_estimados where mes = '${m1}' and concepto = 'ingresos'`) === '44500000.00')
check('la celda muestra el estimado en cursiva', (await celdas('Total ingresos'))[2] === '$44.500.000' && await fila('Total ingresos').locator('td').nth(2).locator('span.italic').count() === 1)
check('quién lo cargó', sql(`select updated_by from cashflow_estimados where mes = '${m1}' and concepto = 'ingresos'`) === '00000000-0000-0000-0000-0000000000f1')
// Escape no guarda
await celdaBtn('Total ingresos', 3).click()
await page.keyboard.type('999'); await page.keyboard.press('Escape')
await page.waitForTimeout(300)
check('Escape cancela', sql(`select count(*) from cashflow_estimados where mes = '${m2}'`) === '0')
// estimado menor que lo ya cargado: manda lo cargado
await celdaBtn('Local y servicios', 2).click()
await page.keyboard.type('1500000'); await page.keyboard.press('Enter')
await page.waitForTimeout(500)
check('si lo cargado supera al estimado, manda lo cargado', (await celdas('Local y servicios'))[2] === '$2.050.000' && sql(`select monto from cashflow_estimados where mes = '${m1}' and concepto = 'local_servicios'`) === '1500000.00')
// borrar un estimado dejando la celda vacía
await celdaBtn('Local y servicios', 2).click()
await page.keyboard.press('Control+A'); await page.keyboard.press('Backspace'); await page.keyboard.press('Enter')
await page.waitForTimeout(500)
check('celda vacía borra el estimado', sql(`select count(*) from cashflow_estimados where concepto = 'local_servicios'`) === '0')

console.log('— estimar filas enteras con aumento mensual')
const estimarFila = async (label, monto, pct, usarPromedio = false) => {
  await fila(label).getByRole('button', { name: /Estimar varios meses/ }).click()
  const modal = page.locator('div.fixed', { hasText: 'Estimar varios meses' }).last()
  if (usarPromedio) await modal.getByRole('button', { name: /Usar el promedio real/ }).click()
  else await modal.locator('label:has-text("Monto del primer mes")').locator('xpath=..').locator('input').fill(String(monto))
  await modal.locator('label:has-text("Aumento por mes")').locator('xpath=..').locator('input').fill(String(pct))
  return modal
}
let modal = await estimarFila('Total ingresos', 42000000, 4)
check('vista previa con aumento compuesto', (await modal.innerText()).includes('$43.680.000') && (await modal.innerText()).includes('$45.427.200'))
await page.screenshot({ path: 'shots/cf-02-estimar-fila.png' })
await modal.getByRole('button', { name: 'Guardar' }).click()
await modal.waitFor({ state: 'detached' })
check('5 meses guardados de una (mes en curso a +4)', sql(`select string_agg(monto::bigint::text, ',' order by mes) from cashflow_estimados where concepto = 'ingresos'`) === '42000000,43680000,45427200,47244288,49134060')
modal = await estimarFila('Personal', 11000000, 5); await modal.getByRole('button', { name: 'Guardar' }).click(); await modal.waitFor({ state: 'detached' })
modal = await estimarFila('Mercadería', 0, 3, true)
const promMerc = Math.round((pagado(mes(-1), ['mercaderia', 'proveedores']) + pagado(mes(-2), ['mercaderia', 'proveedores']) + pagado(mes(-3), ['mercaderia', 'proveedores'])) / 3)
check('sugiere el promedio real de los últimos 3 meses', await modal.locator('label:has-text("Monto del primer mes")').locator('xpath=..').locator('input').inputValue() === String(promMerc), String(promMerc))
await modal.getByRole('button', { name: 'Guardar' }).click(); await modal.waitFor({ state: 'detached' })
for (const [label, monto] of [['Local y servicios', 3200000], ['Impuestos y tasas', 2900000], ['Comisiones y financieros', 1300000], ['Operativos', 850000]]) {
  modal = await estimarFila(label, monto, 3); await modal.getByRole('button', { name: 'Guardar' }).click(); await modal.waitFor({ state: 'detached' })
}
await page.waitForTimeout(500)
check('estimados cargados para 7 filas', sql('select count(distinct concepto) from cashflow_estimados') === '7')
// borrar un rango
modal = await estimarFila('Operativos', 1, 0)
await modal.getByRole('button', { name: 'Borrar estimados del rango' }).click(); await modal.waitFor({ state: 'detached' })
check('borrar estimados del rango', sql("select count(*) from cashflow_estimados where concepto = 'operativos'") === '0')
modal = await estimarFila('Operativos', 850000, 3); await modal.getByRole('button', { name: 'Guardar' }).click(); await modal.waitFor({ state: 'detached' })

console.log('— saldo y alertas')
await page.getByRole('button', { name: 'Saldo y alertas' }).click()
modal = page.locator('div.fixed', { hasText: 'Saldo y alertas' }).last()
await modal.locator('label:has-text("Saldo inicial")').locator('xpath=..').locator('input').fill('2.800.000')
await modal.locator('label:has-text("Saldo mínimo")').locator('xpath=..').locator('input').fill('6000000')
await modal.getByRole('button', { name: 'Guardar' }).click(); await modal.waitFor({ state: 'detached' })
await page.waitForTimeout(700)
check('config guardada', sql('select saldo_inicial||\'|\'||saldo_desde||\'|\'||saldo_minimo from cashflow_config') === `2800000.00|${m0}|6000000.00`)
const num = (t) => Number(t.replace(/[^\d-]/g, ''))
const flujo = (await celdas('Flujo neto del mes')).map(num)
const saldo = await celdas('Saldo final')
let esperado = 2800000; const saldosEsp = flujo.slice(1, 6).map(f => (esperado += f))
check('saldo final = saldo inicial + flujo arrastrado', saldo[0] === '—' && saldo.slice(1, 6).map(num).join() === saldosEsp.join(), `${saldo.join(' ')} vs ${saldosEsp.join(' ')}`)
const ingN = (await celdas('Total ingresos')).map(num); const egN = (await celdas('Total egresos')).map(num)
check('flujo = ingresos − egresos en cada mes y en el total', flujo.every((f, i) => f === ingN[i] - egN[i]))
check('total = suma de los meses', ingN[6] === ingN.slice(0, 6).reduce((a, b) => a + b, 0) && egN[6] === egN.slice(0, 6).reduce((a, b) => a + b, 0))
const estados = await celdas('Estado')
check('estado por mes según saldo y mínimo', estados.slice(1, 6).every((e, i) => e === (saldosEsp[i] < 0 ? 'NEGATIVO' : saldosEsp[i] < 6000000 ? 'BAJO MÍNIMO' : 'OK')), estados.join(' '))
check('mínimo de seguridad en su fila', (await celdas('Saldo mínimo de seguridad'))[1] === '$6.000.000')
const indic = await celdas('Personal como % de ingresos')
check('indicador % de personal', indic[2] === `${((num((await celdas('Personal'))[2]) / ingN[2]) * 100).toLocaleString('es-AR', { minimumFractionDigits: 1, maximumFractionDigits: 1 })}%`, indic[2])
check('ya no pide estimar ingresos del mes', await page.getByText(/falta estimar los ingresos del mes/).count() === 0)

console.log('— detalle de una celda')
await fila('Mercadería').locator('td').nth(0).getByRole('button').click()
modal = page.locator('div.fixed', { hasText: 'Mercadería ·' }).last()
await modal.getByText('Pescado y mariscos (1ra quincena)').waitFor()
check('detalle del mes pasado lista los pagos con proveedor', (await modal.innerText()).includes('Pesquera del Litoral') && (await modal.innerText()).includes('Arroz, algas y secos'))
await page.screenshot({ path: 'shots/cf-03-detalle.png' })
await modal.getByRole('button', { name: '×' }).click()
await fila('Mercadería').locator('td').nth(1).getByRole('button', { name: /Ver los pagos/ }).click()
modal = page.locator('div.fixed', { hasText: 'Mercadería ·' }).last()
await modal.getByText('Factura vencida de secos').waitFor()
check('detalle del mes en curso incluye lo vencido impago', true)
await modal.getByRole('button', { name: '×' }).click()

console.log('— vista, navegación y detalle en celdas')
await page.getByLabel('Mostrar de qué está hecho cada número').check()
check('detalle en celdas: pagado / a pagar', (await fila('Mercadería').locator('td').nth(1).innerText()).includes('a pagar $640.000'))
await page.getByLabel('Mostrar de qué está hecho cada número').uncheck()
await page.mouse.move(700, 660); await page.waitForTimeout(200)
await page.screenshot({ path: 'shots/cf-04-completo.png', fullPage: true })
await page.getByRole('button', { name: '12 meses' }).click()
await page.waitForTimeout(700)
check('12 meses: 12 columnas + total', (await tabla.locator('thead th').count()) === 14)
check('12 meses: el saldo sigue arrastrado igual', num((await celdas('Saldo final'))[2]) === saldosEsp[0])
await page.screenshot({ path: 'shots/cf-05-doce-meses.png', fullPage: true })
await page.getByRole('button', { name: '6 meses' }).click()
await page.getByRole('button', { name: 'Ver un mes después' }).click(); await page.getByRole('button', { name: 'Ver un mes después' }).click()
await page.waitForTimeout(700)
check('flechas mueven la ventana; el saldo se arrastra aunque el mes de arranque ya no se vea', num((await celdas('Saldo final'))[0]) === saldosEsp[1], `${(await celdas('Saldo final'))[0]} vs ${saldosEsp[1]}`)
await page.getByRole('button', { name: 'Volver a hoy' }).click()
await page.waitForTimeout(600)

console.log('— Excel')
const dl = page.waitForEvent('download', { timeout: 20000 })
await page.getByRole('button', { name: 'Exportar Excel' }).click()

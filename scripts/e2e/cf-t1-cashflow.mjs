check('Excel: mismos ingresos que la pantalla', filaX('Total ingresos').slice(1, 8).join() === ingN.join(), filaX('Total ingresos').join(' '))
check('Excel: mismo saldo final', filaX('SALDO FINAL').slice(2, 7).join() === saldosEsp.join())
check('Excel: grupos y estado', filaX('Comisiones y financieros').length === 8 && ['OK', 'BAJO MÍNIMO', 'NEGATIVO'].includes(filaX('Estado')[2]))
check('nombre del archivo', /cashflow_\d{4}-\d{2}_\d{4}-\d{2}\.xlsx$/.test(archivo.suggestedFilename()), archivo.suggestedFilename())

check('sin errores de consola', errores.length === 0, errores.join(' | '))
await browser.close()


// Parte 2 — Mozo cobra la mesa 7 ($50.000) entera a cuenta corriente, con Factura A.
import { abrir, BASE, sql, check, resumen } from './lib.mjs'
const { browser, page, errores } = await abrir('mozo')
await page.goto(BASE + '/mesas', { waitUntil: 'networkidle' })
await page.getByText('7', { exact: true }).first().click()
await page.getByRole('button', { name: 'Cobrar', exact: true }).click()
await page.getByText('Cobrar mesa').waitFor()
await page.waitForTimeout(500)
const modal = page.locator('div.fixed', { hasText: 'Cobrar mesa' }).last()
check('aparece el medio Cuenta corriente', await modal.getByRole('button', { name: 'Cuenta corriente' }).count() === 1)
check('factura arranca en B', (await modal.getByRole('button', { name: /Factura B \+ ticket fiscal/ }).count()) === 1)
await modal.getByRole('button', { name: 'Cuenta corriente' }).click()
check('sin cuenta elegida no deja cobrar', await modal.getByRole('button', { name: /Cerrar mesa sin imprimir/ }).isDisabled())
const sel = modal.getByLabel('Cuenta corriente')
const opciones = await sel.locator('option').evaluateAll(os => os.map(o => `${o.textContent}${o.disabled ? ' [off]' : ''}`))
console.log('   opciones:', opciones.join(' / '))
check('cuenta vencida deshabilitada', opciones.some(o => /Influencer Caro · vencida \[off\]/.test(o)))
check('cuenta vigente muestra saldo', opciones.some(o => /Revista Punto Biz · saldo \$382\.300,00$/.test(o)))
await sel.selectOption({ label: 'Revista Punto Biz · saldo $382.300,00' })
await modal.getByPlaceholder('Ej: V-0012').fill('V-002')
check('muestra lo que le queda', await modal.getByText('Le quedan $332.300,00').count() === 1)
check('Factura A precargada', await modal.getByRole('button', { name: /Factura A \+ ticket fiscal \+ cerrar mesa/ }).count() === 1)
check('CUIT de la cuenta precargado', await modal.locator('input[placeholder="30712345678"]').inputValue() === '30712345671')
check('razón social precargada', await modal.locator('input[placeholder="Empresa SRL"]').inputValue() === 'Punto Biz SA')
await page.screenshot({ path: 'shots/05-cobrar-mesa-cuenta.png' })
await modal.getByRole('button', { name: /Factura A \+ ticket fiscal \+ cerrar mesa/ }).click()
await page.getByText('Cobrar mesa').waitFor({ state: 'detached', timeout: 15000 }).catch(() => {})
await page.waitForTimeout(800)
const err = await page.locator('div.fixed', { hasText: 'Cobrar mesa' }).count() ? await modal.innerText() : ''
check('el modal se cerró', !err, err.slice(-300))

const P = "'10000000-0000-0000-0000-000000000007'"
check('pago registrado', sql(`select medio_pago||'|'||monto||'|'||numero_operacion||'|'||(cuenta_corriente_id is not null)||'|'||(caja_turno_id is not null)||'|'||(comprobante_id is not null) from pagos where pedido_id = ${P}`) === 'cuenta_corriente|50000.00|V-002|true|true|true')
check('movimiento creado por el trigger', sql(`select detalle||'|'||monto||'|'||numero_operacion||'|'||(fecha = (select business_date from caja_turnos limit 1))||'|'||usuario_id from cuenta_corriente_movimientos where pedido_id = ${P}`) === 'Mesa 7 · Orden #9007|50000.00|V-002|true|00000000-0000-0000-0000-0000000000b1')
check('saldo descontado', sql("select saldo from cuentas_corrientes_saldos where nombre = 'Revista Punto Biz'") === '332300.00')
check('pedido cerrado con su valor real', sql(`select estado||'|'||total||'|'||descuento_porcentaje from pedidos where id = ${P}`) === 'entregado|50000.00|0.00')
check('Factura A al CUIT de la cuenta', sql(`select letra||'|'||tipo_cbte||'|'||doc_tipo||'|'||doc_nro||'|'||receptor_nombre||'|'||importe_total from comprobantes_fiscales where pedido_id = ${P}`) === 'A|1|80|30712345671|Punto Biz SA|50000.00')
check('mesa 7 quedó libre', sql("select estado_mesa from v_mesas_estado where numero = 7") === 'libre')
check('sin errores de consola', errores.length === 0, errores.join(' | '))
await browser.close()
process.exit(resumen() ? 1 : 0)

// N° de comprobante a la vista y buscable en Pagos, "Facturas y pagos" en la
// ficha del proveedor, y el formato del mail al crear un usuario.
import { abrir, BASE, sql as sqlBase, check, resumen } from './lib.mjs'
const DB = process.env.DB || 'kkadm'
const sql = (q) => sqlBase(q, DB)
async function hasta(fn, ms = 8000) {
  const fin = Date.now() + ms
  for (;;) { const v = await fn(); if (v || Date.now() > fin) return v; await new Promise(r => setTimeout(r, 200)) }
}
const txt = async (loc) => (await loc.innerText()).replace(/\s+/g, ' ')

const { browser, page, errores } = await abrir('admin', { viewport: { width: 1360, height: 1100 } })

console.log('— Caja → Pagos: el N° de comprobante en la línea')
await page.goto(BASE + '/caja', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: /^Pagos$/ }).click()
const fila = (texto) => page.locator('div.rounded-xl', { hasText: texto }).last()
await page.getByText('QUESOS').first().waitFor()
check('la fila muestra el número de la factura', /QUESOS · La Serenísima S\.A\..*Transferencia.*Comp\. A 0003-00012345/.test(await txt(fila('QUESOS'))), await txt(fila('QUESOS')))
check('un pago sin comprobante no muestra nada de más', !/Comp\./.test(await txt(fila('Hielo'))), await txt(fila('Hielo')))
check('los pendientes también lo muestran', /Comp\. A 0003-00012400/.test(await txt(fila('LECHE Y CREMA'))) && /pendiente/.test(await txt(fila('LECHE Y CREMA'))))
await fila('QUESOS').scrollIntoViewIfNeeded()
await page.screenshot({ path: 'shots/adm-4-pagos-comprobante.png' })
const buscador = page.getByLabel('Buscar pago')
check('el buscador avisa que busca por N° de factura', /N° de factura/.test(await buscador.getAttribute('placeholder')))
await buscador.fill('12345')
await hasta(async () => (await page.locator('[data-comprobante]').count()) === 1)
check('buscar por un pedazo del número encuentra esa factura', await page.locator('[data-comprobante]').count() === 1 && await page.getByText('QUESOS').count() === 1 && await page.getByText('Hielo').count() === 0)
await buscador.fill('0001-00000077')
await hasta(async () => (await page.getByText('Arroz').count()) === 1 && (await page.getByText('QUESOS').count()) === 0)
check('y por el número completo, la de otro proveedor', await page.getByText('Arroz').count() === 1 && /1 pago de 4/.test(await txt(page.locator('main'))))
await buscador.fill('serenisima 0003')
await hasta(async () => (await page.locator('[data-comprobante]').count()) === 2)
check('se combina con el proveedor, sin acentos', await page.locator('[data-comprobante]').count() === 2)
await buscador.fill('')

console.log('— Proveedores → ficha → Facturas y pagos')
await page.goto(BASE + '/proveedores', { waitUntil: 'networkidle' })
const prov = (nombre) => page.locator('div.rounded-xl.overflow-hidden', { hasText: nombre }).first()
await prov('La Serenísima S.A.').waitFor()
await prov('La Serenísima S.A.').locator('button').first().click()
const bloque = prov('La Serenísima S.A.').locator('[data-pagos-proveedor]')
await bloque.waitFor()
const b = await txt(bloque)
check('resumen: pagado, pendiente y vencido', /Pagado \$127\.686/.test(b) && /Pendiente \$80\.000/.test(b) && /\$80\.000 vencido/.test(b), b)
check('cada factura con su número, lo más nuevo primero', b.indexOf('Hielo') < b.indexOf('QUESOS') && b.indexOf('QUESOS') < b.indexOf('LECHE Y CREMA') && /Comp\. A 0003-00012345 · QUESOS Transferencia \$117\.686/.test(b), b)
check('la pendiente dice cuándo vence', /Comp\. A 0003-00012400 · LECHE Y CREMA pendiente · vence \d\d\/\d\d\/\d{4} \$80\.000/.test(b), b)
check('la que no tiene número lo dice', /Sin N° de comprobante · Hielo/.test(b), b)
check('no mezcla pagos de otro proveedor', !/Arroz/.test(b))
await bloque.scrollIntoViewIfNeeded()
await page.screenshot({ path: 'shots/adm-5-proveedor-facturas.png' })
await prov('Verdulería Don Tito').locator('button').first().click()
const vacio = prov('Verdulería Don Tito').locator('[data-pagos-proveedor]')
await vacio.waitFor()
check('un proveedor sin pagos lo dice y explica dónde se cargan', /Todavía no hay facturas ni pagos cargados/.test(await txt(vacio)) && /Registrar pago/.test(await txt(vacio)))
check('sin errores de consola (admin)', errores.length === 0, errores.join(' || '))
await browser.close()

console.log('— un rol que ve Proveedores pero no la plata')
sql("insert into rol_permisos (rol_id, recurso_id, ver, editar) values ('cocina', 'proveedores', true, false) on conflict (rol_id, recurso_id) do update set ver = true")
sql("insert into auth.users (id, email, raw_app_meta_data) values ('00000000-0000-0000-0000-0000000000c1','cocina@kiku.test','{\"role\":\"cocina\"}') on conflict do nothing")
const { USERS } = await import('./lib.mjs')
USERS.cocina = { id: '00000000-0000-0000-0000-0000000000c1', email: 'cocina@kiku.test', role: 'cocina' }
const coc = await abrir('cocina', { viewport: { width: 1360, height: 1000 } })
await coc.page.goto(BASE + '/proveedores', { waitUntil: 'networkidle' })
const provC = coc.page.locator('div.rounded-xl.overflow-hidden', { hasText: 'La Serenísima S.A.' }).first()
await provC.waitFor()
await provC.locator('button').first().click()
await coc.page.waitForTimeout(1200)
check('no ve "Facturas y pagos"', await coc.page.locator('[data-pagos-proveedor]').count() === 0 && await coc.page.getByText('QUESOS').count() === 0)
check('y la base tampoco le da los pagos', sql("select count(*) from rol_permisos rp join recurso_tablas rt on rt.recurso_id = rp.recurso_id where rp.rol_id = 'cocina' and rt.tabla = 'egresos' and rp.ver") === '0')
await coc.browser.close()

console.log('— Finanzas → Resumen → Historial de pagos, y Nuevo usuario')
const fin = await abrir('finanzas', { viewport: { width: 1360, height: 1300 } })
await fin.page.goto(BASE + '/finanzas', { waitUntil: 'networkidle' })
await fin.page.getByText('QUESOS').first().waitFor({ timeout: 15000 })
const historial = fin.page.locator('div.rounded-xl', { has: fin.page.getByText(/Historial de pagos/) }).last()
check('el historial de Finanzas también muestra el comprobante', /Comp\. A 0003-00012345/.test(await txt(historial)), (await txt(historial)).slice(0, 300))
await fin.page.goto(BASE + '/personal', { waitUntil: 'networkidle' })
await fin.page.getByRole('button', { name: /^Usuarios/ }).first().click()
await fin.page.getByRole('button', { name: /Nuevo usuario/ }).click()
const nuevo = fin.page.locator('.fixed.inset-0', { hasText: 'Nuevo usuario' }).last()
await nuevo.waitFor()
check('el mail propone nombreapellido@kikusushi.com.ar', await nuevo.locator('input[type="email"]').getAttribute('placeholder') === 'nombreapellido@kikusushi.com.ar')
const ayuda = await txt(nuevo)
check('y explica la regla', /Nombre y apellido de la persona, todo junto, en minúsculas y sin acentos: juanperez@kikusushi\.com\.ar/.test(ayuda) && /Sin apodos/.test(ayuda), ayuda.slice(0, 400))
await fin.page.screenshot({ path: 'shots/adm-6-nuevo-usuario.png' })
await fin.browser.close()
process.exit(resumen() ? 1 : 0)

// Parte 2 — Admin cierra un take away ($36.500) a cuenta corriente con ticket no fiscal.
import { abrir, BASE, sql, check, resumen } from './lib.mjs'
const { browser, page, errores } = await abrir('admin')
await page.goto(BASE + '/pedidos', { waitUntil: 'networkidle' })
await page.waitForTimeout(800)
await page.locator('tr', { hasText: '2x Philadelphia x10' }).locator('button[title="Cerrar pedido"]').click()
const modal = page.locator('div.fixed', { hasText: 'Medio de pago' }).last()
await modal.getByRole('button', { name: 'Cuenta corriente' }).waitFor()
check('arranca en efectivo y deja cerrar', !(await modal.getByRole('button', { name: 'Cerrar pedido' }).isDisabled()))
await modal.getByRole('button', { name: 'Cuenta corriente' }).click()
check('sin cuenta elegida no deja cerrar', await modal.getByRole('button', { name: 'Cerrar pedido' }).isDisabled())
await modal.getByLabel('Cuenta corriente').selectOption({ label: 'Revista Punto Biz · saldo $332.300,00' })
check('muestra lo que le queda', await modal.getByText('Le quedan $295.800,00').count() === 1)
// ticket fiscal → debe venir con Factura A precargada; volvemos a no fiscal
await modal.getByRole('button', { name: 'Ticket fiscal', exact: true }).click()
check('Factura A precargada (ticket fiscal)', await modal.locator('input[placeholder="30712345678"]').inputValue() === '30712345671')
await page.screenshot({ path: 'shots/06-cerrar-pedido-cuenta.png' })
await modal.getByRole('button', { name: 'Ticket no fiscal' }).click()
await modal.getByRole('button', { name: 'Cerrar pedido' }).click()
await modal.waitFor({ state: 'detached', timeout: 15000 }).catch(() => {})
await page.waitForTimeout(600)
check('el modal se cerró', await page.locator('div.fixed', { hasText: 'Medio de pago' }).count() === 0)
const P = "'10000000-0000-0000-0000-000000000009'"
check('pago registrado', sql(`select medio_pago||'|'||monto||'|'||coalesce(numero_operacion,'-')||'|'||(cuenta_corriente_id is not null)||'|'||(comprobante_id is null) from pagos where pedido_id = ${P}`) === 'cuenta_corriente|36500.00|-|true|true')
check('movimiento con detalle del canal', sql(`select detalle||'|'||monto from cuenta_corriente_movimientos where pedido_id = ${P}`) === 'Take away · Orden #9009|36500.00')
check('saldo descontado', sql("select saldo from cuentas_corrientes_saldos where nombre = 'Revista Punto Biz'") === '295800.00')
check('pedido cerrado', sql(`select estado||'|'||total from pedidos where id = ${P}`) === 'entregado|36500.00')
check('no se emitió factura', sql(`select count(*) from comprobantes_fiscales where pedido_id = ${P}`) === '0')
check('sin errores de consola', errores.length === 0, errores.join(' | '))
await browser.close()
process.exit(resumen() ? 1 : 0)

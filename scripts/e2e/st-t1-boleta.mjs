// Caja → Pagos → Registrar pago con los productos de la boleta, como admin
// (vinculado al empleado "Ana Encargada"), contra Postgres real.
import { abrir, BASE, sql as sqlBase, check, resumen } from './lib.mjs'
const DB = process.env.DB || 'kkst'
const sql = (q) => sqlBase(q, DB)
const SAL = 'c0000000-0000-0000-0000-000000000001'
const PAL = 'c0000000-0000-0000-0000-000000000003'
const stock = (id) => sql(`select stock_actual || '|' || precio_unitario::numeric(14,2) from stock where id = '${id}'`)

const { browser, page, errores } = await abrir('admin', { viewport: { width: 1360, height: 1100 } })
await page.goto(BASE + '/caja', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: /^Pagos$/ }).click()

const modal = page.locator('.fixed.inset-0').filter({ has: page.getByRole('heading', { name: /Registrar pago|Editar pago/ }) })
const campo = (label) => modal.locator(`xpath=.//label[starts-with(normalize-space(.), "${label}")]/following-sibling::*[1]/descendant-or-self::*[self::input or self::select or self::textarea][1] | .//label[starts-with(normalize-space(.), "${label}")]/following-sibling::select[1]`).first()
const seccion = modal.getByRole('region', { name: 'Productos de la boleta' })
const fila = (nombre) => seccion.locator(`[data-fila="${nombre}"]`)
const cant = (nombre) => fila(nombre).getByLabel(`Cantidad de ${nombre}`)
const precio = (nombre) => fila(nombre).getByLabel(new RegExp(`^Precio por .* de ${nombre}$`))
const guardarBtn = modal.locator('button.w-full').last()
// Espera (hasta 4 s) a que una condición se cumpla: la lista se refresca sola
// después de cada guardado.
const hasta = async (fn) => {
  for (let i = 0; i < 40; i++) { if (await fn()) return true; await page.waitForTimeout(100) }
  return false
}
const agregar = async (texto) => {
  await seccion.getByRole('button', { name: /Agregar otro producto/ }).click()
  await page.keyboard.type(texto); await page.waitForTimeout(150); await page.keyboard.press('Enter')
}
const abrirAlta = async () => {
  await page.getByRole('button', { name: /Registrar pago/ }).first().click()
  await modal.waitFor()
}

console.log('— alta: boleta con dos productos')
await abrirAlta()
await modal.getByRole('button', { name: /Cargar los productos de la boleta/ }).waitFor()
check('categoría Proveedores ofrece cargar productos', await modal.getByRole('button', { name: /Cargar los productos de la boleta/ }).count() === 1)
await campo('Categoría').selectOption('sueldos')
check('en Sueldos no se ofrece', await modal.getByRole('button', { name: /Cargar los productos de la boleta/ }).count() === 0)
await campo('Categoría').selectOption('alquiler')
check('en Alquiler tampoco', await modal.getByRole('button', { name: /Cargar los productos de la boleta/ }).count() === 0)
await campo('Categoría').selectOption('mercaderia')
await modal.getByRole('button', { name: /Cargar los productos de la boleta/ }).click()
await seccion.waitFor()
check('sin proveedor: invita a agregar productos', await hasta(async () => await seccion.getByText(/Agregá los productos de la boleta/).count() === 1))
await campo('Proveedor').selectOption({ label: 'Pescadería Mar' })
await fila('Salmón rosado').waitFor()
check('con proveedor: aparece lo que Inventario tiene anotado para él', await seccion.locator('[data-fila]').count() === 1 && await seccion.getByText('Lo que se le compra a Pescadería Mar (1)').count() === 1)
check('trae el precio cargado en Inventario como sugerencia', await precio('Salmón rosado').inputValue() === '10000' && await fila('Salmón rosado').getByText('Precio cargado en Inventario: $10.000').count() === 1)
check('sin cantidad no suma', (await seccion.locator('[data-total-productos]').innerText()).trim() === '$0')

await cant('Salmón rosado').fill('10')
await precio('Salmón rosado').fill('12000')
check('avisa que el precio cambió', await fila('Salmón rosado').getByText(/El precio cambió de \$10\.000 a \$12\.000/).count() === 1)
await agregar('palt')
await fila('Palta').waitFor()
await cant('Palta').fill('2,5')
await precio('Palta').fill('4000')
check('total = 10 × 12.000 + 2,5 × 4.000', (await seccion.locator('[data-total-productos]').innerText()).trim() === '$130.000')
check('el buscador ya no ofrece lo que está en la lista', await (async () => {
  await seccion.getByRole('button', { name: /Agregar otro producto/ }).click()
  const txt = await page.getByRole('listbox').innerText()
  await page.keyboard.press('Escape')
  return !/Palta|Salmón/.test(txt) && /Arroz para sushi/.test(txt) && !/Roll Kiku/.test(txt)
})())
await campo('Descripción').fill('Boleta pescadería')
check('sin monto no deja guardar', await guardarBtn.isDisabled() && await seccion.getByText('Falta el monto del pago.').count() === 1)
await campo('Monto').fill('125000')
check('si no cierra, lo dice y no deja guardar', await guardarBtn.isDisabled() && await modal.locator('[data-problema-productos]').innerText() === 'Los productos se pasan $5.000 del monto del pago.')
await seccion.getByRole('button', { name: 'Usar $130.000 como monto' }).click()
check('"Usar el total como monto" lo corrige', await campo('Monto').inputValue() === '130000' && await seccion.getByText('Coincide con el monto del pago.').count() === 1)
await campo('Medio de pago').selectOption('transferencia')
await campo('Comprobante').fill('A-0001')
check('el botón dice que carga al stock', (await guardarBtn.innerText()).trim() === 'Registrar pago y cargar al stock')
await page.screenshot({ path: 'shots/st-01-boleta.png' })
await guardarBtn.click()
await modal.waitFor({ state: 'detached' })
await page.getByText(/Entraron 2 productos al stock/).waitFor()
check('aviso: entraron 2 productos al stock', true)
const eg1 = sql("select id from egresos where descripcion = 'Boleta pescadería'")
check('un solo pago, con su comprobante y proveedor', sql(`select count(*) || '|' || max(monto) || '|' || max(comprobante_nro) || '|' || max(categoria) from egresos where descripcion = 'Boleta pescadería'`) === '1|130000.00|A-0001|mercaderia')
check('salmón: 5 + 10 = 15 kg y precio nuevo', stock(SAL) === '15.00|12000.00', stock(SAL))
check('palta: 4 + 2,5 = 6,5 kg y precio nuevo', stock(PAL) === '6.50|4000.00', stock(PAL))
check('movimientos atados al pago, con quién y a qué costo', sql(`select string_agg(tipo || ' ' || cantidad || ' ' || origen || ' ' || usuario_nombre || ' ' || costo_unitario::numeric(14,2) || ' ' || notas, ' / ' order by cantidad desc) from stock_movimientos where egreso_id = '${eg1}'`)
  === 'entrada 10.00 compra Ana Encargada 12000.00 Compra: Pescadería Mar · comp. A-0001 / entrada 2.50 compra Ana Encargada 4000.00 Compra: Pescadería Mar · comp. A-0001')
const filaPago = (texto) => page.locator('div.rounded-xl', { has: page.getByText(texto, { exact: false }) }).filter({ has: page.getByTitle('Corregir este pago') }).last()
check('la lista marca "2 productos al stock"', await hasta(async () => await filaPago('Boleta pescadería').getByText('2 productos al stock').count() === 1))

console.log('— segunda boleta: los habituales aparecen solos')
await abrirAlta()
await campo('Categoría').selectOption('mercaderia')
await modal.getByRole('button', { name: /Cargar los productos de la boleta/ }).click()
await campo('Proveedor').selectOption({ label: 'Pescadería Mar' })
await fila('Palta').waitFor()
check('salmón y palta ya son habituales de Pescadería Mar', await seccion.locator('[data-fila]').count() === 2 && await seccion.getByText('Lo que se le compra a Pescadería Mar (2)').count() === 1)
check('muestra la última compra y su precio', await fila('Salmón rosado').getByText(/Última vez: 10 kg a \$12\.000/).count() === 1 && await precio('Palta').inputValue() === '4000')
await cant('Salmón rosado').fill('2')
await campo('Descripción').fill('Salmón con percepciones')
await campo('Monto').fill('30000')
await campo('Medio de pago').selectOption('transferencia')
check('faltan $6.000: no deja guardar', await guardarBtn.isDisabled() && /les faltan \$6\.000/.test(await modal.locator('[data-problema-productos]').innerText()))
await seccion.getByLabel('La diferencia son impuestos, envío o descuentos').check()
check('marcando que son impuestos o envío, deja', await guardarBtn.isEnabled())
await guardarBtn.click()
await modal.waitFor({ state: 'detached' })
await page.getByText(/Entró 1 producto al stock/).waitFor()
check('solo cuenta la fila con cantidad (la palta quedó vacía)', sql("select count(*) from compra_items ci join egresos e on e.id = ci.egreso_id where e.descripcion = 'Salmón con percepciones'") === '1' && stock(SAL) === '17.00|12000.00' && stock(PAL) === '6.50|4000.00')

console.log('— una boleta guardada con diferencia se puede corregir sin volver a tildar')
await filaPago('Salmón con percepciones').getByTitle('Corregir este pago').click()
await modal.waitFor(); await fila('Salmón rosado').waitFor()
check('abre con la diferencia ya aceptada', await hasta(async () => await seccion.getByLabel('La diferencia son impuestos, envío o descuentos').isChecked()) && await modal.getByRole('button', { name: 'Guardar cambios' }).isEnabled())
await campo('Notas').fill('IIBB + percepción IVA')
await modal.getByRole('button', { name: 'Guardar cambios' }).click()
await modal.waitFor({ state: 'detached' })
check('guarda la nota sin tocar el stock', sql("select notas from egresos where descripcion = 'Salmón con percepciones'") === 'IIBB + percepción IVA' && stock(SAL) === '17.00|12000.00')

console.log('— corregir la boleta')
await filaPago('Boleta pescadería').getByTitle('Corregir este pago').click()
await modal.waitFor()
await fila('Palta').waitFor()
check('al editar abre con los productos que tenía', await cant('Salmón rosado').inputValue() === '10' && await cant('Palta').inputValue() === '2.5' && await precio('Palta').inputValue() === '4000')
const movsAntes = Number(sql('select count(*) from stock_movimientos'))
await campo('Notas').fill('Vino con remito')
await modal.getByRole('button', { name: 'Guardar cambios' }).click()
await modal.waitFor({ state: 'detached' })
await page.getByText('Pago corregido.').waitFor()
check('corregir solo la nota no mueve el stock', Number(sql('select count(*) from stock_movimientos')) === movsAntes && sql(`select notas from egresos where id = '${eg1}'`) === 'Vino con remito')
check('y el aviso no habla de stock', await page.getByText(/al stock con el precio|El stock se actualizó/).count() === 0)

await filaPago('Boleta pescadería').getByTitle('Corregir este pago').click()
await modal.waitFor(); await fila('Palta').waitFor()
await cant('Salmón rosado').fill('8')
await fila('Palta').getByRole('button', { name: 'Quitar Palta' }).click()
await seccion.getByRole('button', { name: 'Usar $96.000 como monto' }).click()
await campo('Motivo del cambio').fill('se contó mal')
await modal.getByRole('button', { name: 'Guardar cambios' }).click()
await modal.waitFor({ state: 'detached' })
await page.getByText(/El stock se actualizó con los cambios de la boleta/).waitFor()
check('salmón 17 − 2 = 15; la palta vuelve a 4 kg y a su precio anterior', stock(SAL) === '15.00|12000.00' && stock(PAL) === '4.00|3000.00', `${stock(SAL)} ${stock(PAL)}`)
check('queda como corrección de compra y compra anulada', sql(`select string_agg(split_part(notas, ':', 1) || ' ' || tipo || ' ' || cantidad, ' / ' order by notas) from stock_movimientos where created_at = (select max(created_at) from stock_movimientos) and origen = 'compra'`) === 'Compra anulada salida 2.50 / Corrección de compra salida 2.00')
check('el pago quedó en $96.000 con el motivo en su historial', sql(`select monto from egresos where id = '${eg1}'`) === '96000.00' && sql(`select count(*) from egresos_auditoria where egreso_id = '${eg1}' and motivo = 'se contó mal'`) === '1')
check('la lista ahora dice "1 producto al stock"', await hasta(async () => await filaPago('Boleta pescadería').getByText('1 producto al stock').count() === 1))

console.log('— sacar los productos de un pago')
await filaPago('Boleta pescadería').getByTitle('Corregir este pago').click()
await modal.waitFor(); await fila('Salmón rosado').waitFor()
await seccion.getByRole('button', { name: 'No cargar productos' }).click()
check('avisa que las cantidades salen del stock', await modal.getByText(/Este pago tenía 1 producto cargado: si\s+guardás sin productos, esas cantidades salen del stock/).count() === 1)
await page.screenshot({ path: 'shots/st-02-sacar-productos.png' })
await modal.getByRole('button', { name: 'Guardar cambios' }).click()
await modal.waitFor({ state: 'detached' })
await page.getByText(/Los productos que tenía la boleta salieron del stock/).waitFor()
check('el pago sigue, sin productos, y el salmón baja a 7', sql(`select count(*) from compra_items where egreso_id = '${eg1}'`) === '0' && sql(`select count(*) from egresos where id = '${eg1}'`) === '1' && stock(SAL) === '7.00|12000.00', stock(SAL))
check('la lista ya no lo marca', await hasta(async () => await filaPago('Boleta pescadería').getByText(/al stock/).count() === 0))

console.log('— anular un pago con productos')
await filaPago('Salmón con percepciones').getByTitle('Anular este pago').click()
const confirmar = page.locator('.fixed.inset-0').filter({ hasText: 'Anular pago' })
check('la confirmación avisa que sale del stock', await confirmar.getByText(/También salen del stock el producto que cargó esta boleta/).count() === 1)
await confirmar.getByRole('button', { name: /^(Anular|Eliminar|Confirmar|Sí)/ }).last().click()
await page.waitForTimeout(900)
check('el salmón vuelve a 5 kg y a su precio original', stock(SAL) === '5.00|10000.00', stock(SAL))
check('el movimiento dice quién anuló', sql("select usuario_nombre || '|' || tipo || '|' || cantidad from stock_movimientos where notas like 'Compra anulada%' order by created_at desc limit 1") === 'Ana Encargada|salida|2.00')

console.log('— efectivo de la caja del día + productos')
await abrirAlta()
await campo('Categoría').selectOption('mercaderia')
await campo('Proveedor').selectOption({ label: 'Verdulería Don Tito' })
await modal.getByRole('button', { name: /Cargar los productos de la boleta/ }).click()
await seccion.waitFor()
await seccion.getByRole('button', { name: /Agregar otro producto/ }).waitFor()
check('proveedor sin compras: lo dice y deja agregar', await seccion.getByText(/Todavía no hay compras cargadas a Verdulería Don Tito/).count() === 1)
await agregar('palta'); await fila('Palta').waitFor()
await cant('Palta').fill('3'); await precio('Palta').fill('3500')
await campo('Descripción').fill('Verdulería')
await campo('Monto').fill('10500')
check('efectivo con turno abierto: sale de la caja del día', await modal.getByText(/Sale de la CAJA DEL DÍA/).count() === 1)
await guardarBtn.click()
await modal.waitFor({ state: 'detached' })
check('descuenta del arqueo y mete la palta', sql("select count(*) from caja_movimientos cm join egresos e on e.id = cm.egreso_id where e.descripcion = 'Verdulería'") === '1' && stock(PAL) === '7.00|3500.00', stock(PAL))

console.log('— Proveedores: qué se le compra a cada uno')
await page.goto(BASE + '/proveedores', { waitUntil: 'networkidle' })
const tarjeta = (nombre) => page.locator('div.rounded-xl.overflow-hidden', { has: page.getByText(nombre, { exact: true }) })
await tarjeta('Verdulería Don Tito').locator('button').first().click()
await tarjeta('Verdulería Don Tito').locator('[data-compras-proveedor]').waitFor()
check('la ficha del proveedor muestra lo último que se le compró', await tarjeta('Verdulería Don Tito').getByText('Palta', { exact: true }).count() === 1
  && await tarjeta('Verdulería Don Tito').getByText(/última vez 3 kg a \$3\.500\/kg/).count() === 1)
await tarjeta('Pescadería Mar').locator('button').first().click()
await tarjeta('Pescadería Mar').locator('[data-compras-proveedor]').waitFor()
check('sin boletas vigentes lo dice (las anuladas no cuentan)', await tarjeta('Pescadería Mar').getByText(/Todavía no hay boletas con productos de este proveedor/).count() === 1)

check('sin errores de consola', errores.length === 0, errores.join(' | '))
await browser.close()
process.exit(resumen() ? 1 : 0)

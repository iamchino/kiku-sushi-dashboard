// Regresión del cobro normal + Caja, arqueo y Excel con canjes cargados.
import { abrir, BASE, sql, check, resumen } from './lib.mjs'
import { createRequire } from 'node:module'
const XLSX = createRequire(new URL('../../package.json', import.meta.url))('xlsx')
const { browser, page, errores } = await abrir('admin')

if (!process.env.SKIP1) {
console.log('— delivery en efectivo (cuenta agotada)')
await page.goto(BASE + '/pedidos', { waitUntil: 'networkidle' })
await page.waitForTimeout(800)
await page.locator('tr', { hasText: '1x Combinado x15' }).locator('button[title="Cerrar pedido"]').click()
var modal = page.locator('div.fixed', { hasText: 'Medio de pago' }).last()
await modal.getByRole('button', { name: 'Cuenta corriente' }).click()
var opciones = await modal.getByLabel('Cuenta corriente').locator('option').evaluateAll(os => os.map(o => `${o.textContent}${o.disabled ? ' [off]' : ''}`))
check('cuenta agotada deshabilitada', opciones.some(o => /Revista Punto Biz · sin saldo \[off\]/.test(o)), opciones.join(' / '))
await modal.getByRole('button', { name: 'Efectivo' }).click()
await modal.getByRole('button', { name: 'No imprimir' }).click()
await modal.getByRole('button', { name: 'Cerrar pedido' }).click()
await modal.waitFor({ state: 'detached', timeout: 15000 }).catch(() => {})
await page.waitForTimeout(500)
check('cobro normal en efectivo intacto', sql("select medio_pago||'|'||monto||'|'||(cuenta_corriente_id is null) from pagos where pedido_id = '10000000-0000-0000-0000-000000000010'") === 'efectivo|28000.00|true')

}

console.log('— Caja: formas de pago')
await page.goto(BASE + '/caja', { waitUntil: 'networkidle' })
await page.waitForTimeout(1500)
const caja = await page.locator('main').innerText()
// plata: efectivo 124.200 + 28.000 = 152.200. canjes: 50.000 + 36.500 + 295.800 = 382.300
check('efectivo = solo plata', /Efectivo\s*2 cobros\s*\$152\.200,00/.test(caja), caja.match(/Efectivo[^]{0,60}/)?.[0])
check('total cobrado no incluye canjes', /Total cobrado\s*\$152\.200,00/.test(caja), caja.match(/Total cobrado[^]{0,40}/)?.[0])
check('canjes aparte', /Cuenta corriente \(canjes\)\s*3 consumos · no es plata\s*\$382\.300,00/.test(caja), caja.match(/Cuenta corriente \(canjes\)[^]{0,80}/)?.[0])
check('vendido incluye los canjes a valor real', /Vendido \(pedidos\)\s*\$534\.500,00/.test(caja), caja.match(/Vendido[^]{0,40}/)?.[0])
await page.screenshot({ path: 'shots/09-caja-formas-de-pago.png' })
// chip de forma de pago de la orden de la mesa 7 → detalle con el nombre de la cuenta
const todos = page.getByRole('button', { name: /^Todos/ })
if (await todos.count()) { await todos.first().click(); await page.waitForTimeout(400) }
const card7 = page.locator('article', { hasText: 'Mesa 7' }).first()
check('la orden muestra el chip Cuenta corriente', await card7.getByText('Cuenta corriente').count() >= 1)
await card7.getByText('Cuenta corriente').first().click()
await page.waitForTimeout(300)
check('detalle dice a qué cuenta', (await card7.innerText()).includes('Revista Punto Biz'), (await card7.innerText()).slice(0, 400))
await card7.scrollIntoViewIfNeeded()
await page.screenshot({ path: 'shots/10-caja-orden.png' })

console.log('— Excel de los contadores')
const dl = page.waitForEvent('download', { timeout: 20000 })
await page.getByRole('button', { name: /Reporte|Excel|contadores/i }).first().click()
const archivo = await dl
await archivo.saveAs('shots/reporte.xlsx')
const wb = XLSX.readFile('shots/reporte.xlsx')
console.log('   hojas:', wb.SheetNames.join(' | '))
check('hoja Cuentas corrientes', wb.SheetNames.includes('Cuentas corrientes'))
check('hoja de movimientos', wb.SheetNames.includes('Cuentas corr. movimientos'))
const cobros = XLSX.utils.sheet_to_json(wb.Sheets['Cobros'])
const cc = cobros.filter(r => r['Medio de pago'] === 'Cuenta corriente')
check('Cobros: 3 filas a cuenta corriente con el nombre', cc.length === 3 && cc.every(r => r['Cuenta corriente'] === 'Revista Punto Biz'), JSON.stringify(cc[0]))
check('Cobros: Factura A en la mesa 7', cobros.some(r => r['Pedido'] === 9007 && r['Comprobante'] === 'Factura A'), JSON.stringify(cobros.find(r => r['Pedido'] === 9007)))
const res = XLSX.utils.sheet_to_json(wb.Sheets['Resumen'], { header: 1 })
const fila = (t) => res.find(r => String(r[0] || '').startsWith(t))
check('Resumen: TOTAL solo plata', fila('TOTAL')?.[2] === 152200, JSON.stringify(fila('TOTAL')))
check('Resumen: canjes aparte', fila('Cuenta corriente (canjes')?.[1] === 3 && fila('Cuenta corriente (canjes')?.[2] === 382300, JSON.stringify(fila('Cuenta corriente (canjes')))
const ctas = XLSX.utils.sheet_to_json(wb.Sheets['Cuentas corrientes'])
const rev = ctas.find(r => r['Cuenta'] === 'Revista Punto Biz')
check('Estado de la cuenta', rev && rev['Monto acordado'] === 500000 && rev['Consumido total'] === 500000 && rev['Saldo'] === 0 && rev['CUIT'] === '30712345671' && rev['Estado'] === 'Agotada', JSON.stringify(rev))
check('Consumido en el período (sin el del cuaderno, que es de octubre)', rev && rev['Consumido en el período'] === 382300, String(rev?.['Consumido en el período']))
check('fila TOTAL de cuentas', ctas.at(-1)['Cuenta'] === 'TOTAL' && ctas.at(-1)['Monto acordado'] === 580000)
const movs = XLSX.utils.sheet_to_json(wb.Sheets['Cuentas corr. movimientos'])
check('movimientos del período con pedido y origen', movs.length === 3 && movs.every(m => m['Origen'] === 'Cobro en caja') && movs.some(m => m['Pedido'] === 9007 && m['Nro. operación'] === 'V-002'), JSON.stringify(movs[0]))

console.log('— Arqueo')
await page.getByRole('button', { name: /Arqueo/ }).first().click()
await page.waitForTimeout(1500)
const arq = await page.locator('main').innerText()
check('efectivo esperado = fondo + efectivo', /Efectivo esperado\s*\$172\.200,00/i.test(arq), arq.match(/Efectivo esperado[^]{0,60}/i)?.[0])
check('ventas cobradas sin canjes', /Ventas cobradas\s*\$152\.200,00\s*2 pagos registrados/i.test(arq), arq.match(/Ventas cobradas[^]{0,120}/i)?.[0])
check('conciliación lista los canjes aparte', /Cuenta corriente\s*3 consumos · canje, no entra al arqueo\s*\$382\.300,00/.test(arq), arq.match(/Cuenta corriente\s*3[^]{0,80}/)?.[0])
check('el detalle nombra la cuenta', arq.includes('Revista Punto Biz - Mesa 7'), arq.match(/Revista Punto Biz[^]{0,60}/)?.[0])
const conc = page.locator('div', { hasText: /^Conciliacion por medio/ }).first()
await page.getByText('Conciliacion por medio').scrollIntoViewIfNeeded()
await page.screenshot({ path: 'shots/11-arqueo.png' })
check('sin errores de consola', errores.length === 0, errores.join(' | '))
await browser.close()
process.exit(resumen() ? 1 : 0)

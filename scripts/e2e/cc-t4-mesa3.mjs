// Parte 2 — Mesa 3 ($420.000): el saldo ($295.800) no alcanza → pago dividido.
import { abrir, BASE, sql, check, resumen } from './lib.mjs'
const { browser, page, errores } = await abrir('mozo')
await page.goto(BASE + '/mesas', { waitUntil: 'networkidle' })
await page.getByText('3', { exact: true }).first().click()
await page.getByRole('button', { name: 'Cobrar', exact: true }).click()
const modal = page.locator('div.fixed', { hasText: 'Cobrar mesa' }).last()
await modal.getByRole('button', { name: 'Cuenta corriente' }).click()
await modal.getByLabel('Cuenta corriente').selectOption({ label: 'Revista Punto Biz · saldo $295.800,00' })
check('avisa que el saldo no alcanza', await modal.getByText(/El saldo no alcanza/).count() === 1)
check('dice cuánto falta', (await modal.getByText(/Faltan \$124\.200,00/).count()) === 1)
const cerrar = modal.getByRole('button', { name: /Cerrar mesa sin imprimir/ })
check('no deja cobrar todo a la cuenta', await cerrar.isDisabled())
await page.screenshot({ path: 'shots/07-saldo-no-alcanza.png' })
await modal.getByRole('button', { name: /cobrar el resto con otro medio/ }).click()
await modal.getByText('Asignado $420.000,00 de $420.000,00').waitFor()
check('queda dividido y cuadra', await modal.getByText('OK', { exact: true }).count() === 1)
const montos = modal.locator('input[placeholder="0"]')
check('línea 1 = saldo de la cuenta', await montos.nth(0).inputValue() === '295800')
check('línea 2 = diferencia en efectivo', await montos.nth(1).inputValue() === '124200')
check('Factura A sigue precargada con la cuenta', await modal.getByRole('button', { name: /Factura A \+ ticket fiscal/ }).count() === 1)
// Intento de cargar de más a la cuenta
await montos.nth(0).fill('300000'); await montos.nth(1).fill('120000')
check('avisa que supera el saldo', await modal.getByText(/Supera el saldo de la cuenta/).count() === 1)
check('bloquea el cobro excedido', await cerrar.isDisabled())
await montos.nth(0).fill('295800'); await montos.nth(1).fill('124200')
check('vuelve a habilitar', !(await cerrar.isDisabled()))
await page.screenshot({ path: 'shots/08-pago-dividido.png' })
await modal.getByRole('button', { name: /Ticket no fiscal \+ cerrar mesa/ }).click()
await modal.waitFor({ state: 'detached', timeout: 15000 }).catch(() => {})
await page.waitForTimeout(700)
check('el modal se cerró', await page.locator('div.fixed', { hasText: 'Cobrar mesa' }).count() === 0)
const P = "'10000000-0000-0000-0000-000000000003'"
check('dos pagos: cuenta + efectivo', sql(`select string_agg(medio_pago||':'||monto||':'||(cuenta_corriente_id is not null), ' ' order by medio_pago) from pagos where pedido_id = ${P}`) === 'cuenta_corriente:295800.00:true efectivo:124200.00:false')
check('un solo movimiento, por lo cargado a la cuenta', sql(`select count(*)||'|'||sum(monto) from cuenta_corriente_movimientos where pedido_id = ${P}`) === '1|295800.00')
check('cuenta agotada', sql("select saldo from cuentas_corrientes_saldos where nombre = 'Revista Punto Biz'") === '0.00')
check('pedido cerrado con su valor real', sql(`select estado||'|'||total from pedidos where id = ${P}`) === 'entregado|420000.00')
check('sin errores de consola', errores.length === 0, errores.join(' | '))
await browser.close()
process.exit(resumen() ? 1 : 0)

// Margen de recetas y combos contra el precio de carta SIN IVA, y la boleta
// con productos: el precio va sin IVA y la diferencia con el monto es el IVA
// (la captura de Yamile: 10 u a $1.375,54 = $13.755,40 y pago de $16.644,03).
import { abrir, BASE, sql as sqlBase, check, resumen } from './lib.mjs'
const DB = process.env.DB || 'kkfz'
const sql = (q) => sqlBase(q, DB)
async function hasta(fn, ms = 8000) {
  const fin = Date.now() + ms
  for (;;) { const v = await fn(); if (v || Date.now() > fin) return v; await new Promise(r => setTimeout(r, 200)) }
}
const txt = async (loc) => (await loc.innerText()).replace(/\s+/g, ' ')
const TAPAS = 'c2000000-0000-0000-0000-000000000003'

const { browser, page, errores } = await abrir('admin', { viewport: { width: 1360, height: 1100 } })
await page.goto(BASE + '/recetas', { waitUntil: 'networkidle' })
const main = page.locator('main')
const fila = (nombre) => page.locator('tr', { has: page.locator('td', { hasText: nombre }) }).first()
const margenDe = async (nombre) => txt(fila(nombre).locator('[data-margen]'))
await fila('Roll Kiku').waitFor({ timeout: 15000 })

console.log('— Recetas: el margen se calcula contra el precio sin IVA')
check('la columna se llama "Margen sin IVA"', /MARGEN SIN IVA/i.test(await txt(page.locator('thead'))), await txt(page.locator('thead')))
// Roll Kiku: costo $4.000, carta $12.100 (= $10.000 + IVA) → 60,0 %. Con el precio con IVA daba 66,9 %.
check('Roll Kiku: 60,0 % (antes 66,9 %)', await margenDe('Roll Kiku') === '60.0%' && /\$4\.000/.test(await txt(fila('Roll Kiku'))) && /\$12\.100/.test(await txt(fila('Roll Kiku'))), await txt(fila('Roll Kiku')))
// Empanada: costo $2.282, carta $3.630 (= $3.000 + IVA) → 23,9 %: bajo. Con IVA daba 37,1 % y no avisaba.
check('Empanada Copetín: 23,9 % y marcada como margen bajo (antes 37,1 %, sin aviso)', await margenDe('Empanada Copetín') === '23.9%' && await fila('Empanada Copetín').locator('[data-margen] svg').count() === 1, await txt(fila('Empanada Copetín')))
check('con variantes, la fila usa la primera (x2: 50,0 %)', await margenDe('Nigiri Salmón') === '50.0%')
check('el contador de margen bajo aclara "sin IVA"', /1 con margen bajo \(<30%, sin IVA\)/.test(await txt(main)), (await txt(main)).match(/\d+ con margen bajo[^R]*/)?.[0])
check('el globito explica qué compara', await fila('Roll Kiku').locator('[data-margen]').getAttribute('title') === 'Margen sin IVA: el costo contra el precio de carta sin el IVA')
await page.screenshot({ path: 'shots/fz-10-recetas-margen.png' })

console.log('— dentro de la ficha')
await fila('Roll Kiku').getByTitle('Editar receta').click()
const modalR = page.locator('.fixed.inset-0').filter({ hasText: 'Editar receta' }).last()
await modalR.waitFor()
await hasta(async () => /Margen sin IVA/.test(await txt(modalR)))
check('muestra el precio de carta y el precio sin IVA', /Precio de venta \$12\.100 sin IVA \$10\.000/.test(await txt(modalR)), (await txt(modalR)).match(/Precio de venta.{0,60}/)?.[0])
check('y el margen sin IVA', /Margen sin IVA: 60\.0%/.test(await txt(modalR)))
await modalR.locator('[data-precio-sin-iva]').scrollIntoViewIfNeeded()
await page.screenshot({ path: 'shots/fz-11-ficha-margen.png' })
await page.keyboard.press('Escape')
await modalR.getByRole('button', { name: /Cancelar/ }).click().catch(() => {})
await modalR.waitFor({ state: 'hidden' }).catch(() => {})
if (await modalR.count()) await page.reload({ waitUntil: 'networkidle' })
await fila('Nigiri Salmón').waitFor()
await fila('Nigiri Salmón').getByTitle('Editar receta').click()
const modalN = page.locator('.fixed.inset-0').filter({ hasText: 'Editar receta' }).last()
await modalN.waitFor()
await hasta(async () => /Margen por tamaño/i.test(await txt(modalN)))
const tn = await txt(modalN)
check('por tamaño: x2 50,0 % y x4 42,9 %, con el precio sin IVA al lado', /Margen por tamaño · sin IVA/i.test(tn) && /x2 ?Costo: \$1000 · Venta: \$2\.420 \(sin IVA \$2\.000\) 50\.0%/.test(tn) && /x4 ?Costo: \$2000 · Venta: \$4\.235 \(sin IVA \$3\.500\) 42\.9%/.test(tn), tn.match(/Margen por tamaño.{0,220}/i)?.[0])
await page.reload({ waitUntil: 'networkidle' })

console.log('— Bebidas y reventa, y combos')
await page.getByRole('button', { name: /Bebidas y reventa/ }).click()
await fila('Malbec Reserva').waitFor()
check('Malbec: costo $9.000, carta $18.150 ($15.000 sin IVA) → 40,0 %', await margenDe('Malbec Reserva') === '40.0%', await txt(fila('Malbec Reserva')))
await page.getByRole('button', { name: /^Combos/ }).click()
await fila('Combo Kiku').waitFor()
check('Combo Kiku: costo $8.000, carta $24.200 ($20.000 sin IVA) → 60,0 %', await margenDe('Combo Kiku') === '60.0%' && /\$8\.000/.test(await txt(fila('Combo Kiku'))), await txt(fila('Combo Kiku')))
await fila('Combo Kiku').locator('td').last().locator('button').first().click()
const modalC = page.locator('.fixed.inset-0').filter({ hasText: 'Editar combo' }).last()
await modalC.waitFor()
await hasta(async () => /Margen sin IVA/.test(await txt(modalC)))
check('el combo muestra el precio sin IVA y su margen', /Precio de venta \$24\.200 sin IVA \$20\.000/.test(await txt(modalC)) && /Margen sin IVA: 60\.0%/.test(await txt(modalC)), (await txt(modalC)).match(/Precio de venta.{0,80}/)?.[0])

console.log('— la boleta con productos: el precio va sin IVA')
await page.goto(BASE + '/caja', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: /^Pagos$/ }).click()
await page.getByRole('button', { name: /Registrar pago/ }).first().click()
const modal = page.locator('.fixed.inset-0').filter({ has: page.getByRole('heading', { name: /Registrar pago/ }) })
await modal.waitFor()
const campo = (label) => modal.locator(`xpath=.//label[starts-with(normalize-space(.), "${label}")]/following-sibling::*[1]/descendant-or-self::*[self::input or self::select or self::textarea][1] | .//label[starts-with(normalize-space(.), "${label}")]/following-sibling::select[1]`).first()
await campo('Categoría').selectOption('mercaderia')
await campo('Medio de pago').selectOption('transferencia')
await campo('Descripción').fill('Tapas de copetín')
await modal.getByRole('button', { name: /Cargar los productos de la boleta/ }).click()
const seccion = modal.getByRole('region', { name: 'Productos de la boleta' })
await seccion.waitFor()
check('la sección dice que el precio va sin IVA y en la unidad de Inventario', /El precio va sin IVA, como figura en cada renglón de la factura, y en la unidad de Inventario\. El IVA queda en la diferencia con el monto del pago/.test(await txt(seccion.locator('[data-ayuda-iva]'))), await txt(seccion))
await seccion.getByRole('button', { name: /Agregar otro producto/ }).click()
await page.keyboard.type('Tapas'); await page.waitForTimeout(200); await page.keyboard.press('Enter')
const filaP = seccion.locator('[data-fila="Tapas Empanadas Copetín"]')
await filaP.waitFor()
await filaP.getByLabel('Cantidad de Tapas Empanadas Copetín').fill('10')
await filaP.getByLabel(/^Precio por .* de Tapas Empanadas Copetín$/).fill('1375.54')
await campo('Monto').fill('16644.03')
await hasta(async () => (await seccion.locator('[data-diferencia-iva]').count()) === 1)
const ts = await txt(seccion)
check('avisa cuánto falta para llegar al monto', /A los productos les faltan \$2\.889 para llegar al monto del pago/.test(ts), ts.slice(-400))
check('y reconoce que esa diferencia es justo el IVA', /Esa diferencia es justo el 21% de los productos: es el IVA de la factura\. Tildá la casilla y se guarda con la diferencia/.test(await txt(seccion.locator('[data-diferencia-iva]'))), await txt(seccion.locator('[data-diferencia-iva]')))
check('sin tildar no deja guardar', await modal.locator('button.w-full').last().isDisabled())
await seccion.getByLabel(/La diferencia son impuestos/).check()
check('al tildar, confirma que está bien', /Está bien así: se guarda con la diferencia/.test(await txt(seccion.locator('[data-diferencia-iva]'))) && await modal.locator('button.w-full').last().isEnabled())
await seccion.scrollIntoViewIfNeeded()
await page.screenshot({ path: 'shots/fz-12-boleta-iva.png' })
// Con una diferencia que no es el IVA (flete), no dice nada del IVA.
await campo('Monto').fill('18000')
await page.waitForTimeout(300)
check('si la diferencia no es el 21 %, no habla de IVA', await seccion.locator('[data-diferencia-iva]').count() === 0)
await campo('Monto').fill('16644.03')
await hasta(async () => (await seccion.locator('[data-diferencia-iva]').count()) === 1)
await modal.locator('button.w-full').last().click()
await modal.waitFor({ state: 'hidden' })
check('el pago queda por lo que se pagó (con IVA) y el costo, sin IVA', sql(`select e.monto || '|' || ci.subtotal || '|' || ci.precio_unitario::numeric(14,2) from egresos e join compra_items ci on ci.egreso_id = e.id where e.descripcion = 'Tapas de copetín'`) === '16644.03|13755.40|1375.54', sql(`select e.monto || '|' || ci.subtotal from egresos e join compra_items ci on ci.egreso_id = e.id where e.descripcion = 'Tapas de copetín'`))
check('el stock sube 10 y el precio de costo pasa a $1.375,54', sql(`select stock_actual || '|' || precio_unitario::numeric(14,2) from stock where id = '${TAPAS}'`) === '40.00|1375.54', sql(`select stock_actual || '|' || precio_unitario from stock where id = '${TAPAS}'`))
check('sin errores de consola', errores.length === 0, errores.join(' || '))
await browser.close()
process.exit(resumen() ? 1 : 0)

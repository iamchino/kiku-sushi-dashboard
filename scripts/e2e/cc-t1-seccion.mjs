// Parte 1 — Dinero → Cuentas corrientes, como admin, contra Postgres real.
import { abrir, BASE, sql, check, resumen } from './lib.mjs'
const { browser, page, errores } = await abrir('admin')
const campo = (label) => page.locator(`label:has-text("${label}")`).locator('xpath=..').locator('input, select, textarea').first()

await page.goto(BASE + '/cuentas-corrientes', { waitUntil: 'networkidle' })
await page.getByText('Todavía no hay cuentas corrientes').waitFor()
await page.screenshot({ path: 'shots/01-vacio.png' })

console.log('— alta de cuenta')
await page.getByRole('button', { name: 'Nueva cuenta' }).click()
await campo('Nombre de la cuenta').fill('Revista Punto Biz')
await campo('Monto acordado').fill('500000')
await campo('Vigente hasta').fill('2027-10-31')
await campo('Notas del acuerdo').fill('Canje anual: 2 páginas de publicidad por año a cambio de consumo en el local.')
await campo('Razón social').fill('Punto Biz SA')
await campo('CUIT').fill('30-71234567-8')          // dígito verificador mal
await campo('Condición frente al IVA').selectOption({ label: 'Responsable Inscripto' })
await page.getByRole('button', { name: 'Crear cuenta' }).click()
check('CUIT inválido se rechaza', await page.getByText('El CUIT no es válido').count() === 1)
await campo('CUIT').fill('30712345671')
await campo('Domicilio').fill('Córdoba 1452, Rosario')
await page.screenshot({ path: 'shots/02-nueva-cuenta.png' })
await page.getByRole('button', { name: 'Crear cuenta' }).click()
await page.getByRole('heading', { name: 'Revista Punto Biz' }).waitFor()
check('cuenta guardada en la base', sql("select nombre||'|'||monto_acordado||'|'||cuit||'|'||condicion_iva||'|'||vigencia_hasta from cuentas_corrientes") === 'Revista Punto Biz|500000.00|30712345671|1|2027-10-31')
check('created_by = admin', sql('select created_by from cuentas_corrientes') === '00000000-0000-0000-0000-0000000000a1')

console.log('— consumo manual (el cuaderno)')
await page.getByRole('button', { name: 'Agregar consumo' }).click()
await campo('Fecha').fill('2026-10-20')
await campo('Monto').fill('117.700')
await campo('Detalle').fill('Primer canje (venía del cuaderno)')
await campo('Nro. de operación').fill('V-001')
check('preview de saldo', await page.getByText('$382.300,00').count() >= 1)
await page.screenshot({ path: 'shots/03-agregar-consumo.png' })
await page.getByRole('button', { name: 'Agregar', exact: true }).click()
await page.getByText('Primer canje (venía del cuaderno)').waitFor()
check('movimiento en la base', sql("select fecha||'|'||monto||'|'||numero_operacion||'|'||(pago_id is null) from cuenta_corriente_movimientos") === '2026-10-20|117700.00|V-001|true')
check('saldo en la vista', sql('select consumido||\'|\'||saldo from cuentas_corrientes_saldos') === '117700.00|382300.00')
check('saldo en pantalla', (await page.locator('section').filter({ hasText: 'Consumos (1)' }).innerText()).includes('$382.300,00'))

console.log('— devolución, edición y borrado')
await page.getByRole('button', { name: 'Agregar consumo' }).click()
await page.getByRole('button', { name: /Devolución a favor/ }).click()
await campo('Monto').fill('5000')
await campo('Detalle').fill('Devolución de prueba')
await page.getByRole('button', { name: 'Agregar', exact: true }).click()
await page.getByText('Devolución de prueba').waitFor()
check('devolución guarda monto negativo', sql("select monto from cuenta_corriente_movimientos where detalle = 'Devolución de prueba'") === '-5000.00')
check('saldo sube', sql('select saldo from cuentas_corrientes_saldos') === '387300.00')
// editar la devolución → 7000
await page.locator('tr', { hasText: 'Devolución de prueba' }).getByRole('button', { name: 'Editar consumo' }).click()
await campo('Monto').fill('7000')
await page.getByRole('button', { name: 'Guardar cambios' }).click()
await page.waitForTimeout(600)
check('edición del movimiento', sql("select monto from cuenta_corriente_movimientos where detalle = 'Devolución de prueba'") === '-7000.00')
await page.locator('tr', { hasText: 'Devolución de prueba' }).getByRole('button', { name: 'Borrar consumo' }).click()
await page.getByRole('button', { name: 'Eliminar' }).click()
await page.waitForTimeout(600)
check('borrado del movimiento', sql('select count(*) from cuenta_corriente_movimientos') === '1')
check('saldo vuelve', sql('select saldo from cuentas_corrientes_saldos') === '382300.00')

console.log('— segunda cuenta, duplicado, vencida')
await page.getByRole('button', { name: 'Nueva cuenta' }).click()
await campo('Nombre de la cuenta').fill('revista punto biz')
await campo('Monto acordado').fill('1000')
await page.getByRole('button', { name: 'Crear cuenta' }).click()
await page.getByText('Ya hay una cuenta con ese nombre').waitFor()
check('nombre duplicado se rechaza con mensaje claro', true)
await campo('Nombre de la cuenta').fill('Influencer Caro')
await campo('Monto acordado').fill('80000')
await campo('Vigente hasta').fill('2026-10-31')
await page.getByRole('button', { name: 'Crear cuenta' }).click()
await page.getByRole('heading', { name: 'Influencer Caro' }).waitFor()
check('cuenta vencida marcada', await page.getByText('Vencida').count() >= 1)
check('sin datos fiscales avisa', await page.getByText('Sin datos fiscales').count() === 1)

console.log('— tercera cuenta: desactivar / activar / borrar')
await page.getByRole('button', { name: 'Nueva cuenta' }).click()
await campo('Nombre de la cuenta').fill('Proveedor de prueba')
await campo('Monto acordado').fill('10000')
await page.getByRole('button', { name: 'Crear cuenta' }).click()
await page.getByRole('heading', { name: 'Proveedor de prueba' }).waitFor()
await page.getByRole('button', { name: 'Desactivar' }).click()
await page.getByRole('button', { name: 'Activar', exact: true }).waitFor()
check('desactivada en la base', sql("select activa from cuentas_corrientes where nombre = 'Proveedor de prueba'") === 'f')
check('aparece el filtro de inactivas', await page.getByText('Mostrar también las inactivas').count() === 1)
await page.getByRole('button', { name: 'Activar', exact: true }).click()
await page.getByRole('button', { name: 'Desactivar' }).waitFor()
await page.getByRole('button', { name: 'Borrar', exact: true }).click()
await page.getByRole('button', { name: 'Eliminar' }).click()
await page.waitForTimeout(600)
check('cuenta sin consumos se borra', sql("select count(*) from cuentas_corrientes where nombre = 'Proveedor de prueba'") === '0')
await page.getByRole('button', { name: /Revista Punto Biz/ }).first().click()
check('con consumos no ofrece Borrar', await page.getByRole('button', { name: 'Borrar', exact: true }).count() === 0)
await page.waitForTimeout(400)
await page.screenshot({ path: 'shots/04-seccion.png', fullPage: true })

check('sin errores de consola', errores.length === 0, errores.join(' | '))
await browser.close()
process.exit(resumen() ? 1 : 0)

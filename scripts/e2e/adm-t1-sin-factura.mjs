// Marca "no se factura" en Caja (SQL 58): marcar con motivo, listas, totales,
// volver atrás y que una factura posterior mande sobre la marca.
import { abrir, BASE, sql as sqlBase, check, resumen } from './lib.mjs'
const DB = process.env.DB || 'kkadm'
const sql = (q) => sqlBase(q, DB)
async function hasta(fn, ms = 8000) {
  const fin = Date.now() + ms
  for (;;) { const v = await fn(); if (v || Date.now() > fin) return v; await new Promise(r => setTimeout(r, 200)) }
}

const { browser, page, errores } = await abrir('admin', { viewport: { width: 1360, height: 1100 } })
await page.goto(BASE + '/caja', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Hoy', exact: true }).click()
const tarjeta = (titulo) => page.locator('div.rounded-lg', { has: page.getByText(titulo, { exact: true }) }).last()
const txt = async (loc) => (await loc.innerText()).replace(/\s+/g, ' ')
const orden = (mesa) => page.locator('article', { hasText: `Mesa ${mesa}` }).first()
const filtro = (nombre) => page.getByRole('button', { name: nombre, exact: true })
await hasta(async () => /Pedidos 5/.test(await txt(tarjeta('Facturación'))))

console.log('— antes de marcar')
let f = await txt(tarjeta('Facturación'))
check('Pendientes 4, Facturados 1 y la fila nueva "No se facturan" en 0', /Pendientes facturación 4/.test(f) && /Facturados 1/.test(f) && /No se facturan 0/.test(f), f)
check('aparece la lista "No se facturan"', await filtro('No se facturan').count() === 1)
let tot = await txt(tarjeta('Totales'))
check('No facturado = vendido − facturado', /Vendido \(pedidos\) \$549\.500,00/.test(tot) && /No facturado \$534\.500,00/.test(tot) && !/Marcado «no se factura»/.test(tot), tot)
await orden(7).waitFor()
check('los pendientes ofrecen "No se factura"', await orden(7).getByRole('button', { name: 'No se factura', exact: true }).count() === 1)
await filtro('Facturados').click()
await orden(31).waitFor()
check('un pedido facturado no ofrece la marca', await orden(31).getByRole('button', { name: /No se factura|Volver a pendientes/ }).count() === 0)

console.log('— marcar con motivo')
await filtro('Pendientes de facturación').click()
await orden(7).getByRole('button', { name: 'No se factura', exact: true }).click()
const modal = page.getByRole('dialog', { name: 'No se factura' })
await modal.waitFor()
check('el modal muestra el pedido y el monto', /Pedido #0007 · Mesa 7 · \$50\.000,00/.test(await txt(modal)), await txt(modal))
await modal.getByRole('button', { name: 'Marcar como no se factura' }).click()
check('sin motivo no deja', /Escribí el motivo/.test(await txt(modal)) && sql('select count(*) from pedidos_sin_factura') === '0')
await modal.getByRole('button', { name: 'Invitación de la casa' }).click()
check('el motivo sugerido completa el campo', await modal.getByLabel('Motivo').inputValue() === 'Invitación de la casa')
await modal.getByRole('button', { name: 'Marcar como no se factura' }).click()
await modal.waitFor({ state: 'detached' })
await hasta(async () => /No se facturan 1/.test(await txt(tarjeta('Facturación'))))
check('queda guardado con motivo y quién', sql("select motivo || '|' || usuario_nombre from pedidos_sin_factura where pedido_id = '10000000-0000-0000-0000-000000000007'") === 'Invitación de la casa|Noelia Pérez')
f = await txt(tarjeta('Facturación'))
check('Pendientes baja a 3 y "No se facturan" sube a 1', /Pendientes facturación 3/.test(f) && /No se facturan 1/.test(f) && /Pedidos 5/.test(f), f)
check('sale de la lista de pendientes', await orden(7).count() === 0 && await page.locator('article').count() === 3)
check('avisa dónde quedó', await page.getByText(/Pedido #0007 marcado como "no se factura"/).count() === 1)
tot = await txt(tarjeta('Totales'))
check('los totales no cambian: sigue contando como no facturado', /Vendido \(pedidos\) \$549\.500,00/.test(tot) && /No facturado \$534\.500,00/.test(tot), tot)
check('y se ve cuánto de eso está marcado', /↳ Marcado «no se factura» 1 pedido \$50\.000,00/.test(tot), tot)
check('el pedido no se tocó', sql("select total || '|' || estado from pedidos where numero = 9007") === '50000.00|pendiente')

console.log('— lista "No se facturan"')
await filtro('No se facturan').click()
await orden(7).waitFor()
const t7 = await txt(orden(7))
check('muestra la marca con el motivo, quién y cuándo', /No se factura · Invitación de la casa/.test(t7) && /Noelia Pérez · \d\d\/\d\d/.test(t7) && !/Sin CAE/.test(t7), t7)
check('se puede volver atrás o facturar igual', await orden(7).getByRole('button', { name: 'Volver a pendientes' }).count() === 1 && await orden(7).getByRole('button', { name: 'Facturar + ticket' }).count() === 1)
await orden(7).scrollIntoViewIfNeeded()
await page.screenshot({ path: 'shots/adm-1-no-se-factura.png' })

console.log('— segundo pedido: recuerda el último motivo; motivo escrito a mano')
await filtro('Pendientes de facturación').click()
const takeaway = page.locator('article', { hasText: 'Philadelphia x10' }).first()
await takeaway.getByRole('button', { name: 'No se factura', exact: true }).click()
await modal.waitFor()
check('propone el motivo anterior', await modal.getByLabel('Motivo').inputValue() === 'Invitación de la casa')
await page.screenshot({ path: 'shots/adm-2-no-se-factura-modal.png' })
await modal.getByLabel('Motivo').fill('Canje con la revista, ya facturado aparte')
await modal.getByLabel('Motivo').press('Enter')
await modal.waitFor({ state: 'detached' })
await hasta(async () => /No se facturan 2/.test(await txt(tarjeta('Facturación'))))
tot = await txt(tarjeta('Totales'))
check('dos marcados', /↳ Marcado «no se factura» 2 pedidos \$86\.500,00/.test(tot) && /Pendientes facturación 2/.test(await txt(tarjeta('Facturación'))), tot)

console.log('— volver a pendientes')
await filtro('No se facturan').click()
await orden(7).getByRole('button', { name: 'Volver a pendientes' }).click()
await hasta(async () => /No se facturan 1/.test(await txt(tarjeta('Facturación'))))
check('la marca se borra y el pedido vuelve a Pendientes', sql("select count(*) from pedidos_sin_factura where pedido_id = '10000000-0000-0000-0000-000000000007'") === '0' && /Pendientes facturación 3/.test(await txt(tarjeta('Facturación'))))
await filtro('Pendientes de facturación').click()
check('aparece de nuevo en la lista, como estaba', /Sin CAE/.test(await txt(orden(7))))

console.log('— si después se factura igual, la factura manda')
sql(`insert into comprobantes_fiscales (pedido_id, estado, letra, tipo_cbte, punto_venta, numero, importe_neto, importe_iva, importe_total, cae)
     values ('10000000-0000-0000-0000-000000000009', 'autorizado', 'B', 6, 2, 602, 30165.29, 6334.71, 36500, '76000000000602')`)
await page.getByRole('button', { name: 'Actualizar' }).first().click()
await hasta(async () => /Facturados 2/.test(await txt(tarjeta('Facturación'))))
f = await txt(tarjeta('Facturación'))
check('pasa a Facturados y deja de contar como "no se factura"', /Facturados 2/.test(f) && /No se facturan 0/.test(f) && /Pendientes facturación 3/.test(f), f)
check('la marca vieja quedó en la base pero no se muestra', sql('select count(*) from pedidos_sin_factura') === '1' && !/Marcado «no se factura»/.test(await txt(tarjeta('Totales'))))
await filtro('Facturados').click()
check('en Facturados figura con su factura, sin la marca', /B 00002-00000602/.test(await txt(page.locator('article', { hasText: 'Philadelphia x10' }).first())) && await page.locator('[data-sin-factura]').count() === 0)

check('sin errores de consola', errores.length === 0, errores.join(' || '))
await browser.close()

console.log('— en el celular')
const cel = await abrir('admin', { viewport: { width: 390, height: 1400 }, tema: 'light' })
await cel.page.goto(BASE + '/caja', { waitUntil: 'networkidle' })
await cel.page.getByRole('button', { name: 'Hoy', exact: true }).click()
const card = cel.page.locator('article', { hasText: 'Mesa 7' }).first()
await card.waitFor()
const btn = card.getByRole('button', { name: 'No se factura', exact: true })
const caja = await btn.boundingBox()
check('el botón entra en la pantalla', caja && caja.x >= 0 && caja.x + caja.width <= 390, JSON.stringify(caja))
await btn.click()
const modalCel = cel.page.getByRole('dialog', { name: 'No se factura' })
await modalCel.waitFor()
const cajaModal = await modalCel.locator('div.relative').first().boundingBox()
check('el modal entra en el celular', cajaModal && cajaModal.x >= 0 && cajaModal.x + cajaModal.width <= 390, JSON.stringify(cajaModal))
await cel.page.screenshot({ path: 'shots/adm-3-no-se-factura-celular.png' })
check('sin errores de consola (celular)', cel.errores.length === 0, cel.errores.join(' || '))
await cel.browser.close()
process.exit(resumen() ? 1 : 0)
